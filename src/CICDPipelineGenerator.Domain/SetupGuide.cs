            });
            if (spec.Environments.Any(environment => !string.IsNullOrWhiteSpace(environment.HealthCheckUrl)))
            {
                lines.Add("Before the new version gets all the traffic, the environment's health address must answer; when it does not, the previous version keeps the traffic and the run fails.");
            }
        }

        if (lines.Count == 0)
        {
            return;
        }

        text.AppendLine("## Before the first deployment");
        text.AppendLine();
        foreach (var line in lines)
        {
            text.AppendLine("- " + line);
        }

        text.AppendLine();
    }

    private static string KindLabel(FeedKind kind) => kind switch
    {
        FeedKind.AzureArtifacts => "Azure Artifacts",
        FeedKind.GitHubPackages => "GitHub Packages",
        FeedKind.JFrog => "JFrog Artifactory",
        _ => "private",
    };

    private static string GitHubFeedStep(PackageFeed feed) => feed.Kind switch
    {
        FeedKind.GitHubPackages =>
            "the workflow reads the packages with its own `GITHUB_TOKEN` (`packages: read`). In each package's **Package settings → Manage Actions access**, give this repository **Read**.",
        FeedKind.JFrog when Feeds.UsesJFrogOidc(feed, Platform.GitHubActions) =>
            $"the workflow signs in to JFrog with OpenID Connect, no stored secret. In JFrog, **Administration → General Management → Manage Integrations**, create the OpenID Connect integration `{feed.JFrogOidcProvider}` for GitHub (provider URL `https://token.actions.githubusercontent.com`) and an identity mapping for this repository with read access to `{feed.Feed}`.",
        _ => TokenStep(feed, "in **Settings → Secrets and variables → Actions**, add", "as a **secret**"),
    };

    private static string TokenStep(PackageFeed feed, string where, string secret)
    {
        var token = feed.Kind switch
        {
            FeedKind.AzureArtifacts => "an Azure DevOps personal access token with **Packaging (Read)**",
            FeedKind.GitHubPackages => "a GitHub personal access token (classic) with **read:packages**",
            FeedKind.JFrog => "a JFrog access token (or identity token) with read access to the repository",
            _ => "the feed's password or access token",
        };
        var user = feed.Kind == FeedKind.AzureArtifacts || feed.Type == FeedType.Npm
            ? ""
            : $", and the variable `{Feeds.UserVariable(feed)}` with the user name";
        return $"{where} `{Feeds.TokenVariable(feed)}` {secret} with {token}{user}.";
    }


using System.Globalization;
using System.Text;

namespace CICDPipelineGenerator.Domain;

/// <summary>
/// SETUP.md: what to create once, outside the YAML, before the first run. Nothing here holds a secret:
/// sign-in uses federated credentials, so the pipelines never store an Azure password.
/// </summary>
public static class SetupGuide
{
    public const string Path = "SETUP.md";
    private const string Audience = "api://AzureADTokenExchange";

    public static GeneratedFile Generate(PipelineSpec spec)
    {
        var text = new StringBuilder();
        var repository = string.IsNullOrWhiteSpace(spec.Repository) ? "<owner>/<repository>" : spec.Repository;
        var target = spec.Deploy.Target;

        text.AppendLine(CultureInfo.InvariantCulture, $"# Setting up the pipelines for {spec.Name}");
        text.AppendLine();
        text.AppendLine("Generated by CI/CD Pipeline Generator. Do these steps once, before the first run. Values in <angle brackets> are yours to fill in.");
        text.AppendLine();
        text.AppendLine("## What the pipeline does");
        text.AppendLine();
        text.AppendLine(Summary(spec));
        text.AppendLine();

        if (spec.NeedsAzure)
        {
            AzureIdentity(text, spec, repository);
        }
        else if (spec.IsGenericRegistry)
        {
            RegistryAndCluster(text, spec);
        }
        else if (spec.IsStore)
        {
            text.AppendLine("## 1. Store credentials");
            text.AppendLine();
            text.AppendLine(spec.Deploy.Target switch
            {
                Target.GooglePlay => $"Google Play is reached with a service account that has release permission in the Play Console: keep its JSON key in the secret `{Store.PlayKey}`. The first environment uploads the bundle to its track and, with one branch or a tag, each following environment promotes it from the track before. Create the application and upload its first bundle by hand: Google Play only accepts uploads through the API after that.",
                Target.AppStore => $"App Store Connect is reached with an API key (Users and Access → Integrations): keep the key ID, the issuer ID and the contents of the .p8 file in the secrets {string.Join(", ", Store.AppStoreKey.Select(name => $"`{name}`"))}. The first environment uploads the build to TestFlight; each environment with a group gives the build to that group of testers. Sending a build to App Store review stays a step you do in App Store Connect.",
                _ => $"The Microsoft Store is reached with a Microsoft Entra application linked to Partner Center: keep its values in the secrets {string.Join(", ", Store.MicrosoftStore.Select(name => $"`{name}`"))}. An environment with a flight ID publishes to that package flight; without one it publishes the public submission.",
            });
            text.AppendLine();
            if (Store.SigningSecrets(spec) is { Count: > 0 } signing)
            {
                text.AppendLine(spec.Build.Stack == Stack.Android
                    ? $"The build signs the bundle with your upload keystore, kept base64-encoded (`base64 -w0 release.keystore`) in `{signing[0]}`, with {string.Join(", ", signing.Skip(1).Select(name => $"`{name}`"))}."
                    : spec.Build.MobileFramework == MobileFramework.Maui
                    ? $"The build signs with a distribution certificate and a provisioning profile, both kept base64-encoded, and their names: {string.Join(", ", signing.Select(name => $"`{name}`"))}."
                    : $"The build signs with a distribution certificate and a provisioning profile, both kept base64-encoded: {string.Join(", ", signing.Select(name => $"`{name}`"))}. `{spec.Build.ExportOptions}` names the method, the team and the profile.");
                text.AppendLine();
            }
        }
        else if (spec.IsAws || spec.IsGcp)
        {
            CloudIdentity(text, spec, repository);
        }
        else if (spec.IsRemote)
        {
            text.AppendLine("## 1. Servers");
            text.AppendLine();
            text.AppendLine(spec.UsesPowerShell
                ? "A hosted Windows agent reaches each server with PowerShell remoting over HTTPS (WinRM, port 5986), copies the build and runs the deploy there. Each server has an HTTPS WinRM listener with a certificate the agent trusts, and the account in `DEPLOY_USER` (with `DEPLOY_PASSWORD`) may stop and start the application and write its folder."
                : "A hosted agent reaches each server over SSH, copies the build with rsync and runs the deploy there. `DEPLOY_SSH_KEY` is the private key of the account `DEPLOY_SSH_USER`, and `DEPLOY_SSH_KNOWN_HOSTS` holds the servers' host keys (the output of `ssh-keyscan <server>`), so only those servers are trusted. The account owns the application folder, has `rsync` and may run `sudo systemctl stop|start <service>` without a password.");
            text.AppendLine();
            foreach (var environment in spec.Environments)
            {
                text.AppendLine(CultureInfo.InvariantCulture, $"- **{environment.Name}**: {string.Join(", ", environment.Hosts.Select(host => $"`{host}`"))}");
            }

            text.AppendLine();
        }
        else if (spec.IsServer)
        {
            Servers(text, spec);
        }
        else if (target == Target.StaticWebApp)
        {
            text.AppendLine("## 1. Deployment tokens");
            text.AppendLine();
            text.AppendLine("Static Web Apps sign in with a deployment token, not an Azure identity. For each environment, open the static web app in the Azure portal, choose **Manage deployment token** and copy it:");
            text.AppendLine();
            foreach (var environment in spec.Environments)
            {
                text.AppendLine(CultureInfo.InvariantCulture, $"- **{environment.Name}**: the token of `{environment.ResourceName}`.");
            }

            text.AppendLine();
        }

        if (SharedTemplates.Applies(spec) && spec.Platforms.Any(SharedTemplates.Covers))
        {
            text.AppendLine("## Shared templates");
            text.AppendLine();
            text.AppendLine(CultureInfo.InvariantCulture, $"The files listed under `{SharedTemplates.Folder}` belong in the repository `{spec.TemplateRepository}` (branch `{spec.TemplateRef}`), without that folder in their path; this repository keeps only the short file that calls them with the application's name and each environment's resource names. Another application that is built and deployed the same way calls the same template with its own values.");
            text.AppendLine();
            if (spec.Platforms.Contains(Platform.GitHubActions))
            {
                text.AppendLine(CultureInfo.InvariantCulture, $"- **GitHub Actions**: in `{spec.TemplateRepository}`, **Settings → Actions → General → Access** lets the repositories of the organization use its workflows. The environments, variables and secrets stay in this repository.");
            }

            if (spec.Platforms.Contains(Platform.AzureDevOps))
            {
                text.AppendLine(CultureInfo.InvariantCulture, $"- **Azure DevOps**: the pipeline reads `{spec.TemplateRepository}` as an Azure Repos repository (`Project/Repository`); for a GitHub repository, change `type: git` to `type: github` and add `endpoint:` with the service connection's name.");
            }

            if (spec.Platforms.Contains(Platform.GitLab))
            {
                text.AppendLine(CultureInfo.InvariantCulture, $"- **GitLab**: the project `{spec.TemplateRepository}` must be readable by the people who run this pipeline.");
            }

            text.AppendLine();
        }

        foreach (var platform in spec.Platforms.Distinct())
        {
            switch (platform)
            {
                case Platform.GitHubActions:
                    GitHub(text, spec);
                    break;
                case Platform.AzureDevOps:
                    AzureDevOps(text, spec);
                    break;
                case Platform.GitLab:
                    GitLab(text, spec);
                    break;
                default:
                    ShellSetup.Write(text, spec, platform);
                    break;
            }
        }

        PackageFeedSetup(text, spec);
        SecretsSetup(text, spec);
        Prerequisites(text, spec);
        return new(spec.SeveralApps ? $"SETUP-{spec.Name}.md" : Path, text.ToString().Replace("\r\n", "\n"));
    }

    private static string Summary(PipelineSpec spec)
    {
        var build = spec.IsInfrastructure
            ? $"checks the {spec.Deploy.Target} code"
            : spec.IsContainer && !spec.IsAzureContainer
                ? "runs the tests and builds the image"
            : spec.IsAzureContainer
                ? $"runs the tests and builds the image `{Commands.Image(spec, "<commit>")}` in Azure Container Registry"
                : "builds and tests the code and keeps the result (out/app)";
        var order = spec.Flow == Flow.Tag
            ? $"A tag `{spec.TagPattern}` deploys to {string.Join(", then ", spec.Environments.Select(Describe))}; a push to `{spec.MainBranch}` only builds."
            : spec.Flow == Flow.Promotion
            ? $"A push to `{spec.MainBranch}` deploys to {string.Join(", then ", spec.Environments.Select(Describe))}."
            : string.Join(" ", spec.Environments.Select(environment => $"A push to `{environment.Branch}` deploys to {Describe(environment)}."));
        var pullRequests = spec.BuildPullRequests ? " Pull requests only build and test." : "";
        return $"On each run the pipeline {build}. {order}{pullRequests}";
    }

    private static string Describe(EnvironmentSpec environment) => environment.RequireApproval ? $"**{environment.Name}** (after approval)" : $"**{environment.Name}**";

    private static void AzureIdentity(StringBuilder text, PipelineSpec spec, string repository)
    {
        var usesFederation = spec.Platforms.Any(platform => platform is Platform.GitHubActions or Platform.GitLab);
        text.AppendLine("## 1. Azure identity and permissions");
        text.AppendLine();
        if (usesFederation)
        {
            text.AppendLine("GitHub and GitLab sign in to Azure with a user-assigned managed identity and a federated credential (no password is stored). One identity per environment keeps production apart; create them with the Azure CLI:");
            text.AppendLine();
            text.AppendLine("```bash");
            if (spec.Platforms.Contains(Platform.GitHubActions))
            {
                // Repositories created, renamed or transferred since July 2026 carry their IDs in the subject (repo:owner@id/name@id).
                text.AppendLine(CultureInfo.InvariantCulture, $"prefix=$(gh api repos/{repository}/actions/oidc/customization/sub --jq '.sub_claim_prefix // \"repo:{repository}\"')");
                text.AppendLine();
            }

            foreach (var environment in spec.Environments)
            {
                var identity = $"id-{spec.Name}-{environment.Name}-deploy";
                var group = environment.ResourceGroup ?? "<resource-group>";
                text.AppendLine(CultureInfo.InvariantCulture, $"az identity create --name {identity} --resource-group {group}");
                if (spec.Platforms.Contains(Platform.GitHubActions))
                {
                    text.AppendLine(CultureInfo.InvariantCulture, $"az identity federated-credential create --name github-{environment.Name} --identity-name {identity} --resource-group {group} \\");
                    text.AppendLine(CultureInfo.InvariantCulture, $"  --issuer https://token.actions.githubusercontent.com --subject \"$prefix:environment:{environment.Name}\" --audiences {Audience}");
                }

                if (spec.Platforms.Contains(Platform.GitLab))
                {
                    text.AppendLine(CultureInfo.InvariantCulture, $"az identity federated-credential create --name gitlab-{environment.Name} --identity-name {identity} --resource-group {group} \\");
                    text.AppendLine(CultureInfo.InvariantCulture, $"  --issuer https://gitlab.com --subject project_path:{repository}:ref_type:branch:ref:{spec.BranchOf(environment)} --audiences {Audience}");
                }

                text.AppendLine();
            }

            text.AppendLine("```");
            text.AppendLine();
            if (spec.Platforms.Contains(Platform.GitLab))
            {
                text.AppendLine("On a self-managed GitLab, the issuer is your GitLab address instead of https://gitlab.com.");
                text.AppendLine();
            }

            if (spec.IsAzureContainer && spec.Platforms.Contains(Platform.GitHubActions))
            {
                text.AppendLine("The GitHub build job builds the image before any environment, so it signs in with the repository-level identity. Give that identity a federated credential for each branch that deploys:");
                text.AppendLine();
                foreach (var branch in spec.DeployBranches())
                {
                    text.AppendLine(CultureInfo.InvariantCulture, $"- subject `$prefix:ref:refs/heads/{branch}`");
                }

                text.AppendLine();
            }
        }

        text.AppendLine("Give each identity (or Azure DevOps service connection) these roles:");
        text.AppendLine();
        foreach (var line in Roles(spec))
        {
            text.AppendLine("- " + line);
        }

        text.AppendLine();
        text.AppendLine("Assign a role with `az role assignment create --assignee <principal-id> --role \"<role>\" --scope <resource-id>`.");
        text.AppendLine();
    }

    /// <summary>A registry that is not a cloud's own, and a Kubernetes cluster reached with its kubeconfig.</summary>
    private static void RegistryAndCluster(StringBuilder text, PipelineSpec spec)
    {
        var deploy = spec.Deploy;
        var platforms = spec.Platforms.Distinct().ToList();
        text.AppendLine(deploy.Target == Target.Kubernetes ? "## 1. Registry and cluster" : deploy.Target == Target.GitOps ? "## 1. Registry and manifests repository" : "## 1. Registry");
        text.AppendLine();
        text.AppendLine(CultureInfo.InvariantCulture, $"The image is built with Docker and pushed as `{CloudDeploy.Image(spec, "<commit>")}`. Create an access token of the registry that may push, and keep its user and the token in the secrets `{CloudDeploy.RegistryUser}` and `{CloudDeploy.RegistryPassword}`{(deploy.RegistryKind == RegistryKind.GitHub && platforms.Contains(Platform.GitHubActions) ? " (GitHub Actions needs neither: it pushes to ghcr.io with its own `GITHUB_TOKEN`)" : "")}.");
        text.AppendLine();
        if (deploy.Target == Target.Kubernetes)
        {
            text.AppendLine("Each environment's cluster is reached with a kubeconfig kept in the secret `KUBE_CONFIG`, base64-encoded (`base64 -w0 kubeconfig`). Use a service account limited to the namespace, not an administrator's own file, and let the cluster pull from the registry (an `imagePullSecrets` entry when the image is private).");
            text.AppendLine();
            foreach (var platform in platforms)
            {
                text.AppendLine(platform switch
                {
                    Platform.GitHubActions => $"- **GitHub Actions**: an environment secret `KUBE_CONFIG` in each of {string.Join(", ", spec.Environments.Select(environment => $"`{environment.Name}`"))}.",
                    Platform.AzureDevOps => $"- **Azure DevOps**: the secret variables {string.Join(", ", spec.Environments.Select(environment => $"`{Secrets.AzureDevOpsName(environment, "KUBE_CONFIG")}`"))}.",
                    _ => "- **GitLab CI/CD**: the CI/CD variable `KUBE_CONFIG`, once per environment with its **Environment scope**.",
                });
            }

            text.AppendLine();
        }
        else if (deploy.Target == Target.GitOps)
        {
            text.AppendLine(CultureInfo.InvariantCulture, $"Each environment's deploy writes the new tag into its file of `{deploy.GitOpsRepository}` ({string.Join(", ", spec.Environments.Select(environment => $"`{environment.ParametersFile}`"))}) and pushes the commit; Argo CD or Flux follows that repository and updates the cluster. Keep a token that may push to it in the secret `GITOPS_TOKEN`.");
            text.AppendLine();
        }
        else
        {
            text.AppendLine(CultureInfo.InvariantCulture, $"Every environment gives the image of its commit one more tag: {string.Join(", ", spec.Environments.Select(environment => $"`{CloudDeploy.Image(spec, environment.Name)}`"))}.");
            text.AppendLine();
        }
    }

    /// <summary>How each system signs in to AWS or Google Cloud, and what to create for it.</summary>
    private static void CloudIdentity(StringBuilder text, PipelineSpec spec, string repository)
    {
        var platforms = spec.Platforms.Distinct().ToList();
        var environments = string.Join(", ", spec.Environments.Select(environment => $"`{environment.Name}`"));
        if (spec.IsAws)
        {
            text.AppendLine("## 1. AWS identity and permissions");
            text.AppendLine();
            text.AppendLine("Create one IAM role per environment with the permissions the deploy needs (S3, Lambda, Elastic Beanstalk, ECR with ECS or EKS, or what the infrastructure code creates).");
            text.AppendLine();
            if (platforms.Contains(Platform.GitHubActions))
            {
                text.AppendLine(CultureInfo.InvariantCulture, $"- **GitHub Actions** signs in with OpenID Connect: add the identity provider `token.actions.githubusercontent.com` (audience `sts.amazonaws.com`) to IAM, let each role trust the subject `<prefix>:environment:<environment>` (the prefix is `repo:{repository}` on older repositories and `repo:owner@id/name@id` on those created, renamed or transferred since July 2026: `gh api repos/{repository}/actions/oidc/customization/sub --jq .sub_claim_prefix` says it), and keep the role's ARN in the variable `AWS_ROLE_ARN` of each environment ({environments}){(spec.IsContainer ? "; the build job uses the repository-level `AWS_ROLE_ARN`, trusted for the branches that deploy" : "")}.");
            }

            if (platforms.Contains(Platform.GitLab))
            {
                text.AppendLine("- **GitLab CI/CD** signs in with OpenID Connect: add the identity provider `gitlab.com` (audience `https://gitlab.com`) to IAM, let each role trust the project and branch, and keep the role's ARN in the CI/CD variable `AWS_ROLE_ARN`, once per environment with its **Environment scope**.");
            }

            if (platforms.Contains(Platform.AzureDevOps))
            {
                text.AppendLine(CultureInfo.InvariantCulture, $"- **Azure DevOps** has no OpenID Connect sign-in to AWS without an extension: create an IAM user per environment and keep its access key in the secret variables {string.Join(", ", spec.Environments.Select(environment => $"`{Secrets.AzureDevOpsName(environment, "AWS_ACCESS_KEY_ID")}` and `{Secrets.AzureDevOpsName(environment, "AWS_SECRET_ACCESS_KEY")}`"))}.");
            }
        }
        else
        {
            text.AppendLine("## 1. Google Cloud identity and permissions");
            text.AppendLine();
            text.AppendLine("Create one service account per environment with the roles the deploy needs (Cloud Run, Cloud Functions, App Engine or GKE, plus Cloud Build and Artifact Registry for images). Each environment's project is in `GCP_PROJECT_ID`.");
            text.AppendLine();
            if (platforms.Contains(Platform.GitHubActions))
            {
                text.AppendLine(CultureInfo.InvariantCulture, $"- **GitHub Actions** signs in with workload identity federation: create a workload identity pool and provider for `https://token.actions.githubusercontent.com` limited to `{repository}`, let it impersonate the service account, and keep `GCP_WORKLOAD_IDENTITY_PROVIDER` (the provider's full name), `GCP_SERVICE_ACCOUNT` and `GCP_PROJECT_ID` as variables of each environment ({environments}){(spec.IsContainer ? " and of the repository, for the build job" : "")}.");
            }

            if (platforms.Contains(Platform.GitLab))
            {
                text.AppendLine("- **GitLab CI/CD** signs in with workload identity federation: create a pool and provider for `https://gitlab.com` limited to the project, and keep `GCP_WORKLOAD_IDENTITY_PROVIDER` (as `projects/<number>/locations/global/workloadIdentityPools/<pool>/providers/<provider>`), `GCP_SERVICE_ACCOUNT` and `GCP_PROJECT_ID` as CI/CD variables, once per environment with its **Environment scope**.");
            }

            if (platforms.Contains(Platform.AzureDevOps))
            {
                text.AppendLine(CultureInfo.InvariantCulture, $"- **Azure DevOps** signs in with a service account key: keep the key's JSON in the secret variables {string.Join(", ", spec.Environments.Select(environment => $"`{Secrets.AzureDevOpsName(environment, "GCP_CREDENTIALS")}`"))} and the project in {string.Join(", ", spec.Environments.Select(environment => $"`{Secrets.AzureDevOpsName(environment, "GCP_PROJECT_ID")}`"))}.");
            }

            if (spec.IsContainer)
            {
                text.AppendLine();
                text.AppendLine(CultureInfo.InvariantCulture, $"The image is built by Cloud Build from the `Dockerfile` in `{spec.Deploy.DockerContext}` and kept in the Artifact Registry repository `{spec.Deploy.Registry}` ({spec.Deploy.CloudRegion}).");
            }
        }

        text.AppendLine();
    }

    private static void Servers(StringBuilder text, PipelineSpec spec)
    {
        var what = spec.Deploy.Target switch
        {
            Target.WindowsService => "stop and start the Windows service and write its folder (and the folder next to it, which keeps the previous version)",
            Target.LinuxService => "run `sudo systemctl stop|start <service>` without a password and write the service's folder (and the folder next to it, which keeps the previous version); `rsync` is installed",
            Target.ScheduledTask => "disable, stop and enable the scheduled task and write its folder (and the folder next to it, which keeps the previous version)",
            Target.Iis => "stop and start the application pool and write the site folder (and the folder next to it, which keeps the previous version)",
            _ => "run your deploy commands",
        };
        text.AppendLine("## 1. Servers");
        text.AppendLine();
        text.AppendLine(CultureInfo.InvariantCulture, $"The deploy runs on each environment's own servers, in {(spec.UsesPowerShell ? "Windows PowerShell" : "bash")}, through the runner or agent installed on them. Its account must be able to {what}.");
        text.AppendLine();
        foreach (var environment in spec.Environments)
        {
            text.AppendLine(CultureInfo.InvariantCulture, $"- **{environment.Name}**: servers labelled `{environment.ServerLabel}`.");
        }

        text.AppendLine();
    }

    private static IEnumerable<string> Roles(PipelineSpec spec)
    {
        switch (spec.Deploy.Target)
        {
            case Target.Script:
                yield return "The roles your deploy commands need, on the resources they change.";
                break;
            case Target.AppService:
            case Target.FunctionApp:
                yield return "**Website Contributor** on each environment's app.";
                break;
            case Target.ContainerApp:
                yield return "**Contributor** on each environment's container app, and on the Container Apps environment it runs in (changing the app's revision mode or traffic joins it to that environment again, which needs `Microsoft.App/managedEnvironments/join/action`).";
                yield return $"**Contributor** on the registry `{spec.Deploy.Registry}` for the identity that builds the image (`az acr build` runs a registry task, which AcrPush alone does not allow).";
                break;
            case Target.Aks:
                yield return "**Azure Kubernetes Service Cluster User Role** on each cluster.";
                yield return $"**Azure Kubernetes Service RBAC Writer** on the namespace `{spec.Deploy.Namespace}` (clusters that use Azure RBAC), or a Kubernetes role binding for the identity.";
                yield return $"**Contributor** on the registry `{spec.Deploy.Registry}` for the identity that builds the image.";
                break;
            case Target.Terraform when spec.NeedsAzure:
                yield return "**Contributor** on the subscription or resource groups Terraform manages (**Owner** or **Role Based Access Control Administrator** if it also assigns roles).";
                yield return $"**Storage Blob Data Contributor** on the state storage account `{spec.Deploy.StateStorageAccount}`.";
                break;
            case Target.Bicep or Target.ArmTemplate:
                yield return "**Contributor** on each environment's resource group.";
                break;
            case Target.Pulumi:
                yield return "**Contributor** on the subscription or resource groups Pulumi manages (**Owner** or **Role Based Access Control Administrator** if it also assigns roles).";
                break;
        }
    }

    private static void GitHub(StringBuilder text, PipelineSpec spec)
    {
        text.AppendLine("## GitHub Actions");
        text.AppendLine();
        if (SetupScript.Applies(spec))
        {
            text.AppendLine(CultureInfo.InvariantCulture, $"**The short way:** run `bash {SetupScript.Path}` (or `{SetupScript.PowerShellPath(SetupScript.Path)}` in PowerShell) once, signed in to {(spec.IsAws ? "the AWS CLI" : spec.IsGcp ? "`gcloud`" : "`az login`")} and `gh auth login`. It creates each environment's {(spec.IsAws ? "role" : spec.IsGcp ? "service account" : "identity")} with what it trusts and may do, the environments of the repository and their variables, and asks for the value of each secret. The steps below, and the identity section above, are what it does.");
            text.AppendLine();
        }

        var step = 1;
        text.AppendLine(CultureInfo.InvariantCulture, $"{step++}. Commit `{GitHubGenerator.PathFor(spec)}`{(GitHubGenerator.Previews(spec) ? $" and `{GitHubGenerator.PreviewCleanupPathFor(spec)}`" : "")}.");
        if (Quality.CodeQl(spec) is not null)
        {
            text.AppendLine(CultureInfo.InvariantCulture, $"{step++}. CodeQL shows what it finds under **Security → Code scanning**. A private repository needs GitHub Code Security turned on (**Settings → Advanced Security**); public repositories have it.");
        }

        if (GitHubGenerator.ContainerPreviews(spec))
        {
            text.AppendLine(CultureInfo.InvariantCulture, $"{step++}. Every pull request gets a revision of `{spec.Environments[0].ResourceName}` with its own address and no traffic, stopped when it closes. Deploy once from the branch first: that ties the traffic to a revision by name, and a preview refuses to start while the traffic still follows the latest revision. The environment `{spec.Environments[0].Name}` must let pull request branches deploy (no branch rule, no approval). Pull requests from forks get none.");
        }
        else if (GitHubGenerator.Previews(spec))
        {
            text.AppendLine(CultureInfo.InvariantCulture, $"{step++}. Every pull request gets a slot `pr-<number>` of `{spec.Environments[0].ResourceName}`, removed when it closes. Slots need the Standard plan or higher, the environment `{spec.Environments[0].Name}` must let pull request branches deploy (no branch rule, no approval), and its identity needs **Website Contributor** on the application. Pull requests from forks get none.");
        }
        if (spec.Deploy.Target == Target.StaticWebApp)
        {
            text.AppendLine(CultureInfo.InvariantCulture, $"{step++}. In **Settings → Environments**, create each environment and add the secret `AZURE_STATIC_WEB_APPS_API_TOKEN` with its deployment token.");
        }
        else if (spec.NeedsAzure)
        {
            text.AppendLine(CultureInfo.InvariantCulture, $"{step++}. In **Settings → Secrets and variables → Actions → Variables**, add `AZURE_TENANT_ID`, `AZURE_SUBSCRIPTION_ID` and `AZURE_CLIENT_ID` (the client ID of the identity).");
            text.AppendLine(CultureInfo.InvariantCulture, $"{step++}. In **Settings → Environments**, create each environment and add the variable `AZURE_CLIENT_ID` with that environment's identity; it overrides the repository value.");
        }
        else
        {
            text.AppendLine(CultureInfo.InvariantCulture, $"{step++}. In **Settings → Environments**, create each environment ({string.Join(", ", spec.Environments.Select(environment => $"`{environment.Name}`"))}).");
        }

        if (spec.OnServerRunner)
        {
            text.AppendLine(CultureInfo.InvariantCulture, $"{step++}. Each environment's self-hosted runners have the labels `self-hosted`, `{(spec.UsesPowerShell ? "windows" : "linux")}` and the environment's label ({string.Join(", ", spec.Environments.Select(environment => $"`{environment.ServerLabel}`"))}).");
        }

        var approvals = spec.Environments.Where(environment => environment.RequireApproval).Select(environment => $"`{environment.Name}`").ToList();
        if (approvals.Count > 0)
        {
            text.AppendLine(CultureInfo.InvariantCulture, $"{step}. In {string.Join(", ", approvals)}, turn on **Required reviewers** and choose who approves. Optionally limit **Deployment branches** to the branch that deploys.");
        }

        text.AppendLine();
    }

    private static void AzureDevOps(StringBuilder text, PipelineSpec spec)
    {
        text.AppendLine("## Azure DevOps");
        text.AppendLine();
        if (SetupScript.AppliesToAzureDevOps(spec))
        {
            text.AppendLine(CultureInfo.InvariantCulture, $"**The short way:** run `bash {SetupScript.AzureDevOpsPath} https://dev.azure.com/<organization> <project>` (or `{SetupScript.PowerShellPath(SetupScript.AzureDevOpsPath)}` in PowerShell) once, signed in with `az login`. It creates each environment's identity and its service connection with workload identity federation, its role, the environments, the pipeline (for a repository of Azure Repos, which must already hold the pipeline file) with permission to use those connections and environments, and asks for the value of each secret. The steps below are what it does.");
            text.AppendLine();
        }


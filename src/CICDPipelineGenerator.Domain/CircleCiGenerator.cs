namespace CICDPipelineGenerator.Domain;

/// <summary>
/// .circleci/config.yml: one job for the build and one per environment, joined by a workflow. A job signs in to the
/// clouds with its OpenID Connect token; each environment's variables are a context named after the application
/// and the environment; an environment that needs approval waits at an approval job.
/// </summary>
public static class CircleCiGenerator
{
    public const string Path = ".circleci/config.yml";
    private const string Rollback = "<< pipeline.parameters.rollback >>";

    public static string Context(PipelineSpec spec, EnvironmentSpec? environment) => $"{spec.Name}-{environment?.Name ?? "build"}";

    public const string ContinuePath = ".circleci/continue.yml";

    /// <summary>
    /// CircleCI looks at the changed paths in a first, small configuration (its path-filtering orb), which then
    /// continues with the real pipeline only when one of them changed.
    /// </summary>
    public static bool FiltersPaths(PipelineSpec spec) =>
        spec.PathFilters.Count > 0 && spec.Flow != Flow.Tag && string.IsNullOrWhiteSpace(spec.Schedule) && !(spec.Deploy.RollbackPipeline && spec.IsServerApp);

    public static IReadOnlyList<GeneratedFile> GenerateAll(PipelineSpec spec)
    {
        var pipeline = Generate(spec);
        if (!FiltersPaths(spec))
        {
            return [pipeline];
        }

        var setup = new YMap
        {
            { "version", new YScalar("2.1", Raw: true) },
            { "setup", true },
            { "orbs", new YMap { { "path-filtering", "circleci/path-filtering@1" } } },
            {
                "workflows", new YMap
                {
                    {
                        "check-paths", new YMap
                        {
                            {
                                "jobs", new YSeq
                                {
                                    new YMap
                                    {
                                        {
                                            "path-filtering/filter", new YMap
                                            {
                                                { "base-revision", spec.MainBranch },
                                                { "config-path", ContinuePath },
                                                { "mapping", string.Join('\n', spec.PathFilters.Select(path => $"{PathPattern(path)} changed true")) + "\n" },
                                            }
                                        },
                                    },
                                }
                            },
                        }
                    },
                }
            },
        };
        return
        [
            new(Path, YamlWriter.Write(setup, [$"Generated by CI/CD Pipeline Generator for {spec.Name}.", $"It continues with {ContinuePath} when one of the paths changed."])),
            pipeline with { Path = ContinuePath },
        ];
    }

    /// <summary>A path filter as the regular expression the orb matches against each changed file.</summary>
    private static string PathPattern(string path) =>
        string.Concat(System.Text.RegularExpressions.Regex.Split(path, @"(\*\*/?|\*)").Select(part => part switch
        {
            "**" or "**/" => ".*",
            "*" => "[^/]*",
            _ => System.Text.RegularExpressions.Regex.Escape(part),
        }));

    public static GeneratedFile Generate(PipelineSpec spec)
    {
        var plan = ShellPlan.Create(spec, Platform.CircleCi);
        var jobs = new YMap();
        foreach (var job in plan.Jobs.Concat(plan.Rollbacks))
        {
            jobs.Add(job.Id, Job(spec, job));
        }

        var workflows = new YMap();
        var deploy = new YMap();
        if (plan.Rollbacks.Count > 0)
        {
            deploy.Add("when", new YMap { { "equal", new YSeq(["none", Rollback]) } });
        }

        deploy.Add("jobs", Invocations(spec, plan, scheduled: false));
        workflows.Add("deploy", deploy);
        if (!string.IsNullOrWhiteSpace(spec.Schedule))
        {
            workflows.Add("scheduled", new YMap
            {
                {
                    "triggers", new YSeq
                    {
                        new YMap { { "schedule", new YMap { { "cron", new YScalar(spec.Schedule, Raw: false) }, { "filters", new YMap { { "branches", new YMap { { "only", new YSeq(spec.DeployBranches()) } } } } } } } },
                    }
                },
                { "jobs", Invocations(spec, plan, scheduled: true) },
            });
        }

        foreach (var group in plan.Rollbacks.GroupBy(job => job.Environment!))
        {
            // Started by hand: Trigger pipeline, with the parameter rollback set to the environment.
            var list = new YSeq();
            string? previous = null;
            foreach (var job in group)
            {
                list.Add(new YMap { { job.Id, new YMap { { "requires", previous is null ? null : new YSeq([previous]) }, { "context", new YSeq([Context(spec, group.Key)]) } } } });
                previous = job.Id;
            }

            workflows.Add("rollback-" + group.Key.Name, new YMap { { "when", new YMap { { "equal", new YSeq([group.Key.Name, Rollback]) } } }, { "jobs", list } });
        }

        var root = new YMap { { "version", new YScalar("2.1", Raw: true) } };
        if (FiltersPaths(spec))
        {
            // Set by the first configuration when one of the paths changed.
            root.Add("parameters", new YMap { { "changed", new YMap { { "type", "boolean" }, { "default", false } } } });
            deploy.Add("when", "<< pipeline.parameters.changed >>");
        }

        if (plan.Rollbacks.Count > 0)
        {
            root.Add("parameters", new YMap
            {
                {
                    "rollback", new YMap
                    {
                        { "description", "The environment that goes back to its previous version (none runs the normal pipeline)" },
                        { "type", "enum" },
                        { "enum", new YSeq(spec.Environments.Select(environment => environment.Name).Prepend("none")) },
                        { "default", "none" },
                    }
                },
            });
        }

        root.Add("jobs", jobs);
        root.Add("workflows", workflows);
        return new(Path, YamlWriter.Write(root,
        [
            $"Generated by CI/CD Pipeline Generator for {spec.Name}.",
            "Before the first run, follow SETUP.md: contexts, variables and the cloud identity.",
        ]));
    }

    private static YMap Job(PipelineSpec spec, PlanJob job)
    {
        var steps = new YSeq();
        if (job.Checkout)
        {
            steps.Add("checkout");
        }

        if (job.UsesBuild)
        {
            steps.Add(new YMap { { "attach_workspace", new YMap { { "at", "." } } } });
        }

        if (job.Docker)
        {
            steps.Add("setup_remote_docker");
        }

        if (job.Cache is not null)
        {
            steps.Add(new YMap { { "restore_cache", new YMap { { "keys", new YSeq([$"packages-{{{{ .Branch }}}}-", "packages-"]) } } } });
        }

        foreach (var step in job.Steps)
        {
            // Each step is its own shell, so the sign-in comes with every one that follows it.
            var command = (job.Windows ? (step.Script.StartsWith("$ErrorActionPreference", StringComparison.Ordinal) ? "" : "$ErrorActionPreference = 'Stop'\n") : job.Preamble.Length > 0 ? job.Preamble + "\n" : "")
                + Systems.WithEnv(step.Script, step.Env, job.Windows);
            steps.Add(new YMap { { "run", new YMap { { "name", step.Name }, { "command", command } } } });
        }

        if (job.Cache is { } cached)
        {
            steps.Add(new YMap { { "save_cache", new YMap { { "key", "packages-{{ .Branch }}-{{ .Revision }}" }, { "paths", new YSeq(["~/" + PackageCache.Folder(cached)]) } } } });
        }

        if (job.JUnit is not null)
        {
            var folder = Commands.JUnitFolder(spec).StartsWith("**/", StringComparison.Ordinal) ? Commands.Join(spec.Build.WorkingDirectory, Commands.JUnitFolder(spec)[3..]) : Commands.JUnitFolder(spec);
            steps.Add(new YMap { { "store_test_results", new YMap { { "path", folder }, { "when", "always" } } } });
        }

        foreach (var results in job.Results)
        {
            steps.Add(new YMap { { "store_artifacts", new YMap { { "path", results }, { "when", "always" } } } });
        }

        if (job.Keeps.Count > 0)
        {
            steps.Add(new YMap { { "persist_to_workspace", new YMap { { "root", "." }, { "paths", new YSeq(job.Keeps) } } } });
        }

        if (job.NotifiesSuccess)
        {
            steps.Add(new YMap
            {
                {
                    "run", new YMap
                    {
                        { "name", "Tell the team it is deployed" },
                        { "command", $"export WEBHOOK=\"$NOTIFY_WEBHOOK\" TEXT=\"{spec.Name} is deployed to {job.Environment!.Name}: {Systems.RunUrl(Platform.CircleCi)}\"\n{Commands.Notify}" },
                    }
                },
            });
        }

        if (spec.NotifyOnFailure && !job.Windows)
        {
            steps.Add(new YMap
            {
                {
                    "run", new YMap
                    {
                        { "name", "Tell the team it failed" },
                        { "when", "on_fail" },
                        { "command", $"export WEBHOOK=\"$NOTIFY_WEBHOOK\" TEXT=\"The pipeline of {spec.Name} failed: {Systems.RunUrl(Platform.CircleCi)}\"\n{Commands.Notify}" },
                    }
                },
            });
        }

        var result = new YMap();
        if (job.Label is not null)
        {
            // Your own runner: its resource class (namespace/name) is the label.
            result.Add("machine", true);
            result.Add("resource_class", job.Label);
            result.Add("shell", job.Windows ? "powershell.exe -ExecutionPolicy Bypass" : null);
        }
        else if (job.Windows)
        {
            result.Add("machine", new YMap { { "image", "windows-server-2022-gui:current" } });
            result.Add("resource_class", "windows.medium");
            result.Add("shell", "powershell.exe -ExecutionPolicy Bypass");
        }
        else if (job.Mac)
        {
            result.Add("macos", new YMap { { "xcode", new YScalar("16.4.0", Raw: false) } });
            result.Add("resource_class", "m4pro.medium");
        }
        else
        {
            // The first image runs the steps; the others are the services, reached on localhost.
            var images = new YSeq { new YMap { { "image", job.Image } } };
            foreach (var service in job.Services)
            {
                var environment = new YMap();
                foreach (var (key, value) in service.Env)
                {
                    environment.Add(key, value);
                }

                images.Add(new YMap { { "image", service.Image }, { "environment", environment.Count > 0 ? environment : null } });
            }

            result.Add("docker", images);
        }

        result.Add("steps", steps);
        return result;
    }

    /// <summary>The jobs of the workflow in order, with what each one waits for and the branches or tags it runs on.</summary>
    private static YSeq Invocations(PipelineSpec spec, Plan plan, bool scheduled)
    {
        var list = new YSeq();
        var tag = spec.Flow == Flow.Tag && !scheduled;
        var before = new List<string>();
        string? previousDeploy = null;
        EnvironmentSpec? previousEnvironment = null;
        foreach (var job in plan.Jobs)
        {
            var invocation = new YMap();
            var requires = new List<string>();
            if (job.Environment is null)
            {
                requires.AddRange(before);
                before.Add(job.Id);
            }
            else
            {
                // The servers of one environment go one after another; the next environment waits for the last of them.
                var sameEnvironment = previousEnvironment == job.Environment;
                requires.AddRange(previousDeploy is not null && (spec.Promotes || sameEnvironment) ? [previousDeploy] : before);
                if (job.Environment.RequireApproval && !sameEnvironment)
                {
                    var approval = "approve-" + job.Environment.Name;
                    list.Add(new YMap { { approval, new YMap { { "type", "approval" }, { "requires", new YSeq(requires) }, { "filters", Filters(spec, job, tag, scheduled) } } } });
                    requires = [approval];
                }

                previousDeploy = job.Id;
                previousEnvironment = job.Environment;
            }

            invocation.Add("requires", requires.Count > 0 ? new YSeq(requires) : null);
            if (job.Environment is not null || job.Oidc || job.Variables.Count > 0)
            {
                invocation.Add("context", new YSeq([Context(spec, job.Environment)]));
            }

            // One deployment at a time per environment.
            invocation.Add("serial-group", job.Environment is null ? null : $"<< pipeline.project.slug >>/{job.Environment.Name}");
            invocation.Add("filters", Filters(spec, job, tag, scheduled));
            list.Add(new YMap { { job.Id, invocation } });
        }

        return list;
    }

    private static YMap? Filters(PipelineSpec spec, PlanJob job, bool tag, bool scheduled)
    {
        if (scheduled)
        {
            return null;
        }

        var tags = tag ? new YMap { { "only", TagPattern(spec) } } : null;
        if (!job.NotOnPullRequests)
        {
            // The build also runs for other branches (pull requests) when asked; it never deploys from them.
            var branches = spec.BuildPullRequests ? null : new YMap { { "only", new YSeq(spec.DeployBranches()) } };
            return branches is null && tags is null ? null : Map(("branches", branches), ("tags", tags));
        }

        if (tag)
        {
            return Map(("branches", new YMap { { "ignore", new YScalar("/.*/", Raw: false) } }), ("tags", tags));
        }

        var only = job.Environment is null ? spec.DeployBranches() : [spec.BranchOf(job.Environment)];
        return Map(("branches", new YMap { { "only", new YSeq(only) } }));
    }

    private static YMap Map(params (string Key, YNode? Value)[] entries)
    {
        var map = new YMap();
        foreach (var (key, value) in entries)
        {
            map.Add(key, value);
        }

        return map;
    }

    /// <summary>v* becomes the regular expression /^v.*/; a tag without * is that tag exactly.</summary>
    private static YScalar TagPattern(PipelineSpec spec)
    {
        var pattern = spec.TagPattern;
        var text = pattern.EndsWith('*') ? pattern[..^1].Replace(".", "\\.", StringComparison.Ordinal) + ".*" : pattern.Replace(".", "\\.", StringComparison.Ordinal);
        return new YScalar($"/^{text}$/", Raw: false);
    }
}

using System.Text.Json;

namespace CICDPipelineGenerator.Domain;

/// <summary>
/// The pipeline split in two: a template kept in a repository of its own, which takes the application's name and each
/// environment's resource names as parameters, and a short file in the application's repository that calls it with
/// its values. Other applications built and deployed the same way call the same template with theirs.
/// </summary>
public static class SharedTemplates
{
    /// <summary>The files to commit in the templates repository are listed under this folder.</summary>
    public const string Folder = "shared-templates/";
    public const string GitHubPath = ".github/workflows/deploy-template.yml";
    public const string AzurePath = "azure-pipelines-template.yml";
    public const string GitLabPath = "gitlab/deploy-template.yml";

    public static bool Applies(PipelineSpec spec) => !string.IsNullOrWhiteSpace(spec.TemplateRepository) && !spec.SeveralApps;

    public static bool Covers(Platform platform) => platform is Platform.GitHubActions or Platform.AzureDevOps or Platform.GitLab;

    private sealed record Parameter(string Key, string Token, string Value);

    /// <summary>A copy whose name and resource names are marks; in the written template each mark becomes the parameter.</summary>
    private static (PipelineSpec Copy, List<Parameter> Parameters) Mark(PipelineSpec spec)
    {
        var copy = JsonSerializer.Deserialize<PipelineSpec>(JsonSerializer.Serialize(spec, ProposalPrompt.Json), ProposalPrompt.Json)!;
        copy.TemplateRepository = null;
        var parameters = new List<Parameter> { new("name", "zzq-name-zz", spec.Name) };
        copy.Name = parameters[0].Token;
        for (var index = 0; index < copy.Environments.Count; index++)
        {
            var environment = copy.Environments[index];
            var key = environment.Name.Replace('-', '_');
            if (!string.IsNullOrWhiteSpace(environment.ResourceName))
            {
                parameters.Add(new("resource_" + key, $"zzq{index}resourcezz", environment.ResourceName));
                environment.ResourceName = parameters[^1].Token;
            }

            if (!string.IsNullOrWhiteSpace(environment.ResourceGroup))
            {
                parameters.Add(new("group_" + key, $"zzq{index}groupzz", environment.ResourceGroup));
                environment.ResourceGroup = parameters[^1].Token;
            }
        }

        return (copy, parameters);
    }

    private static string Fill(string text, List<Parameter> parameters, Func<string, string> reference) =>
        parameters.Aggregate(text, (current, parameter) => current.Replace(parameter.Token, reference(parameter.Key), StringComparison.Ordinal));

    private static YMap Values(List<Parameter> parameters)
    {
        var values = new YMap();
        foreach (var parameter in parameters)
        {
            values.Add(parameter.Key, parameter.Value);
        }

        return values;
    }

    private static string[] TemplateHeader(PipelineSpec spec) =>
    [
        "Generated by CI/CD Pipeline Generator.",
        $"A shared template: keep it in {spec.TemplateRepository}; each application's own file calls it with its names.",
    ];

    private static string[] CallerHeader(PipelineSpec spec) =>
    [
        $"Generated by CI/CD Pipeline Generator for {spec.Name}.",
        $"It runs the shared template of {spec.TemplateRepository}. Before the first run, follow SETUP.md.",
    ];

    public static IReadOnlyList<GeneratedFile> GitHub(PipelineSpec spec)
    {
        var (copy, parameters) = Mark(spec);
        var root = GitHubGenerator.Root(copy);
        var inputs = new YMap();
        foreach (var parameter in parameters)
        {
            inputs.Add(parameter.Key, new YMap { { "type", "string" }, { "required", true } });
        }

        var template = new YMap
        {
            { "name", "Deploy (shared template)" },
            { "on", new YMap { { "workflow_call", new YMap { { "inputs", inputs } } } } },
            { "permissions", root["permissions"] },
            { "jobs", root["jobs"] },
        };

        // The caller gives the template everything any of its jobs asks for.
        var permissions = new Dictionary<string, string>(StringComparer.Ordinal);
        foreach (var map in ((YMap)root["jobs"]!).Select(job => ((YMap)job.Value)["permissions"]).Prepend(root["permissions"]).OfType<YMap>())
        {
            foreach (var (key, value) in map)
            {
                var level = ((YScalar)value).Text;
                permissions[key] = level == "write" || !permissions.TryGetValue(key, out var current) ? level : current;
            }
        }

        var granted = new YMap();
        foreach (var (key, value) in permissions)
        {
            granted.Add(key, value);
        }

        var caller = new YMap
        {
            { "name", $"Deploy {spec.Name}" },
            { "on", GitHubGenerator.Root(spec)["on"] },
            { "permissions", granted },
            {
                "jobs", new YMap
                {
                    {
                        "pipeline", new YMap
                        {
                            { "uses", $"{spec.TemplateRepository}/{GitHubPath}@{spec.TemplateRef}" },
                            { "with", Values(parameters) },
                            { "secrets", "inherit" },
                        }
                    },
                }
            },
        };
        return
        [
            new(GitHubGenerator.PathFor(spec), YamlWriter.Write(caller, CallerHeader(spec))),
            new(Folder + GitHubPath, Fill(YamlWriter.Write(template, TemplateHeader(spec)), parameters, key => $"${{{{ inputs.{key} }}}}")),
        ];
    }

    public static IReadOnlyList<GeneratedFile> AzureDevOps(PipelineSpec spec)
    {
        var (copy, parameters) = Mark(spec);
        var declared = new YSeq();
        foreach (var parameter in parameters)
        {
            declared.Add(new YMap { { "name", parameter.Key }, { "type", "string" } });
        }

        var template = new YMap { { "parameters", declared }, { "stages", AzureDevOpsGenerator.Root(copy)["stages"] } };
        var own = AzureDevOpsGenerator.Root(spec);
        var caller = new YMap();
        foreach (var (key, value) in own.Where(pair => pair.Key is not ("stages" or "resources")))
        {
            caller.Add(key, value);
        }

        caller.Add("resources", new YMap
        {
            // An Azure Repos repository as Project/Repository; for GitHub, use type github and name its service connection as endpoint.
            { "repositories", new YSeq { new YMap { { "repository", "templates" }, { "type", "git" }, { "name", spec.TemplateRepository }, { "ref", "refs/heads/" + spec.TemplateRef } } } },
            { "containers", (own["resources"] as YMap)?["containers"] },
        });
        caller.Add("extends", new YMap { { "template", AzurePath + "@templates" }, { "parameters", Values(parameters) } });
        return
        [
            new(AzureDevOpsGenerator.PathFor(spec), YamlWriter.Write(caller, CallerHeader(spec))),
            new(Folder + AzurePath, Fill(YamlWriter.Write(template, TemplateHeader(spec)), parameters, key => $"${{{{ parameters.{key} }}}}")),
        ];
    }

    public static IReadOnlyList<GeneratedFile> GitLab(PipelineSpec spec)
    {
        var (copy, parameters) = Mark(spec);
        var caller = new YMap
        {
            {
                "include", new YSeq
                {
                    new YMap { { "project", spec.TemplateRepository }, { "ref", spec.TemplateRef }, { "file", "/" + GitLabPath }, { "inputs", Values(parameters) } },
                }
            },
        };

        // A template with inputs has two parts: what it takes, then the pipeline.
        var taken = "spec:\n  inputs:\n" + string.Concat(parameters.Select(parameter => $"    {parameter.Key}:\n")) + "---\n";
        return
        [
            new(GitLabGenerator.PathFor(spec), YamlWriter.Write(caller, CallerHeader(spec))),
            new(Folder + GitLabPath, taken + Fill(YamlWriter.Write(GitLabGenerator.Root(copy), TemplateHeader(spec)), parameters, key => $"$[[ inputs.{key} ]]")),
        ];
    }
}

namespace CICDPipelineGenerator.Domain;

/// <summary>
/// bitbucket-pipelines.yml: the build step, then one deployment step per environment. A step signs in to the clouds
/// with its own OpenID Connect token (oidc: true); variables are repository variables for the build and deployment
/// variables for each environment; an environment that needs approval is a manual step.
/// </summary>
public static class BitbucketGenerator
{
    public const string Path = "bitbucket-pipelines.yml";

    public static GeneratedFile Generate(PipelineSpec spec)
    {
        var plan = ShellPlan.Create(spec, Platform.Bitbucket);
        var build = plan.Jobs.Where(job => job.Environment is null).ToList();
        var pipelines = new YMap();
        if (spec.BuildPullRequests)
        {
            pipelines.Add("pull-requests", new YMap { { "**", Steps(spec, build.Where(job => !job.NotOnPullRequests)) } });
        }

        var branches = new YMap();
        if (spec.Flow == Flow.Tag)
        {
            // Pushes to the branch only build; a tag builds and deploys every environment in order.
            branches.Add(spec.MainBranch, Steps(spec, build.Where(job => !job.NotOnPullRequests)));
            pipelines.Add("branches", branches);
            pipelines.Add("tags", new YMap { { spec.TagPattern, Steps(spec, plan.Jobs) } });
        }
        else
        {
            foreach (var branch in spec.DeployBranches())
            {
                branches.Add(branch, Steps(spec, plan.Jobs.Where(job => job.Environment is null || spec.BranchOf(job.Environment) == branch)));
            }

            pipelines.Add("branches", branches);
        }

        if (plan.Rollbacks.Count > 0)
        {
            // Started by hand: Pipelines → Run pipeline → choose the branch and this pipeline.
            var custom = new YMap();
            foreach (var group in plan.Rollbacks.GroupBy(job => job.Environment!.Name))
            {
                custom.Add("rollback-" + group.Key, Steps(spec, group));
            }

            pipelines.Add("custom", custom);
        }

        var root = new YMap();
        var definitions = new YMap();
        if (build[0].Cache is { } stack)
        {
            definitions.Add("caches", new YMap { { "packages", "~/" + PackageCache.Folder(stack) } });
        }

        if (Services.All(spec) is { Count: > 0 } all)
        {
            var services = new YMap();
            foreach (var service in all)
            {
                var variables = new YMap();
                foreach (var (key, value) in service.Env)
                {
                    variables.Add(key, value);
                }

                services.Add(service.Name, new YMap { { "image", service.Image }, { "variables", variables.Count > 0 ? variables : null } });
            }

            definitions.Add("services", services);
        }

        if (definitions.Count > 0)
        {
            root.Add("definitions", definitions);
        }

        root.Add("pipelines", pipelines);
        return new(Path, YamlWriter.Write(root,
        [
            $"Generated by CI/CD Pipeline Generator for {spec.Name}.",
            "Before the first run, follow SETUP.md: variables, deployment environments and the cloud identity.",
        ]));
    }

    /// <summary>The steps in order; the servers of one environment share its deployment as a stage.</summary>
    private static YSeq Steps(PipelineSpec spec, IEnumerable<PlanJob> jobs)
    {
        var steps = new YSeq();
        foreach (var group in jobs.GroupBy(job => job.Environment?.Name ?? job.Id))
        {
            var list = group.ToList();
            var environment = list[0].Environment;
            if (environment is null)
            {
                steps.Add(new YMap { { "step", Step(spec, list[0]) } });
            }
            else if (list.Count == 1)
            {
                var step = Step(spec, list[0]);
                step.Add("deployment", environment.Name);
                step.Add("trigger", environment.RequireApproval && !list[0].IsRollback ? "manual" : null);
                steps.Add(new YMap { { "step", step } });
            }
            else
            {
                // A deployment belongs to one step or one stage, so several servers are the steps of a stage.
                var stage = new YMap
                {
                    { "name", (list[0].IsRollback ? "Roll back " : "Deploy to ") + environment.Name },
                    { "deployment", environment.Name },
                    { "trigger", environment.RequireApproval && !list[0].IsRollback ? "manual" : null },
                };
                var inner = new YSeq();
                foreach (var job in list)
                {
                    inner.Add(new YMap { { "step", Step(spec, job) } });
                }

                stage.Add("steps", inner);
                steps.Add(new YMap { { "stage", stage } });
            }
        }

        return steps;
    }

    private static YMap Step(PipelineSpec spec, PlanJob job)
    {
        var script = new YSeq();
        if (job.Preamble.Length > 0)
        {
            script.Add("# Sign in\n" + job.Preamble);
        }

        foreach (var step in job.Steps)
        {
            script.Add($"# {step.Name}\n" + (job.Windows && !step.Script.StartsWith("$ErrorActionPreference", StringComparison.Ordinal) ? "$ErrorActionPreference = 'Stop'\n" : "") + Systems.WithEnv(step.Script, step.Env, job.Windows));
        }

        var artifacts = new YSeq(job.Keeps.Concat(job.Results).Select(folder => folder + "/**"));
        if (job.JUnit is not null && spec.Build.PublishTestResults)
        {
            artifacts.Add(job.JUnit);
        }

        var step2 = new YMap
        {
            { "name", job.Name },
            { "image", job.Label is null ? job.Image : null },
            // Your own runners: a build agent, or the runner installed on the environment's server.
            { "runs-on", job.Label is null ? null : new YSeq(["self.hosted", job.Windows ? "windows" : job.Mac ? "macos" : "linux", job.Label]) },
            { "oidc", job.Oidc ? (YNode)true : null },
            { "services", job.Docker || job.Services.Count > 0 ? new YSeq(job.Services.Select(service => service.Name).Concat(job.Docker ? ["docker"] : [])) : null },
            { "caches", job.Cache is null ? null : new YSeq(["packages"]) },
            { "clone", job.Checkout || job.Environment is null ? null : new YMap { { "enabled", false } } },
            { "condition", spec.PathFilters.Count > 0 && spec.Flow != Flow.Tag && !job.IsRollback ? new YMap { { "changesets", new YMap { { "includePaths", new YSeq(spec.PathFilters) } } } } : null },
            { "script", script },
            { "artifacts", artifacts.Count > 0 ? artifacts : null },
        };
        var after = new YSeq();
        if (spec.NotifyOnFailure && !job.Windows)
        {
            after.Add($"if [ \"$BITBUCKET_EXIT_CODE\" != 0 ]; then\n  export WEBHOOK=\"$NOTIFY_WEBHOOK\" TEXT=\"The pipeline of {spec.Name} failed: {Systems.RunUrl(Platform.Bitbucket)}\"\n  {Commands.Notify}\nfi");
        }

        if (job.NotifiesSuccess)
        {
            after.Add($"if [ \"$BITBUCKET_EXIT_CODE\" = 0 ]; then\n  export WEBHOOK=\"$NOTIFY_WEBHOOK\" TEXT=\"{spec.Name} is deployed to {job.Environment!.Name}: {Systems.RunUrl(Platform.Bitbucket)}\"\n  {Commands.Notify}\nfi");
        }

        step2.Add("after-script", after.Count > 0 ? after : null);

        return step2;
    }
}

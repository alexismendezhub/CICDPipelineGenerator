namespace CICDPipelineGenerator.Domain;

/// <summary>
/// .gitlab-ci.yml: build and deploy stages, one deploy job per environment. Azure sign-in uses a GitLab ID token
/// (OpenID Connect) with the CI/CD variables AZURE_CLIENT_ID, AZURE_TENANT_ID and AZURE_SUBSCRIPTION_ID, which can be
/// scoped per environment; an environment that needs approval waits for someone to press its play button.
/// </summary>
public static class GitLabGenerator
{
    public const string Path = ".gitlab-ci.yml";

    /// <summary>With several applications in the repository, each one has its own file.</summary>
    public static string PathFor(PipelineSpec spec) => spec.SeveralApps ? $"ci/{spec.Name}.gitlab-ci.yml" : Path;
    private const string Sha = "$CI_COMMIT_SHA";
    private const string AzureCliImage = "mcr.microsoft.com/azure-cli:latest";
    private const string NotMergeRequest = "$CI_PIPELINE_SOURCE != \"merge_request_event\"";

    public static GeneratedFile Generate(PipelineSpec spec) => new(PathFor(spec), YamlWriter.Write(Root(spec),
    [
        $"Generated by CI/CD Pipeline Generator for {spec.Name}.",
        "Before the first run, follow SETUP.md: Azure identity, CI/CD variables and protected environments.",
    ]));

    internal static YMap Root(PipelineSpec spec)
    {
        var root = new YMap
        {
            { "workflow", new YMap { { "rules", WorkflowRules(spec) } } },
            { "stages", new YSeq(spec.Deploy.RollbackPipeline && spec.IsServerApp ? ["build", "deploy", "rollback"] : ["build", "deploy"]) },
            { ".azure", AzureTemplate() },
        };

        var buildJobs = BuildJobs(spec);
        foreach (var (version, other) in Services.Versions(spec))
        {
            // The deploy needs them too, so it waits for the tests with every version.
            buildJobs.Add((Services.Id(version), BuildJobs(other)[0].Job));
        }

        foreach (var (name, job) in buildJobs)
        {
            root.Add(name, job);
        }

        var lastBuild = buildJobs.Select(job => job.Name).ToList();
        string? previous = null;
        foreach (var environment in spec.Environments)
        {
            var needs = new YSeq(lastBuild);
            if (spec.Promotes && previous is not null)
            {
                needs.Add(previous);
            }

            var id = JobId(environment);
            root.Add(id, DeployJob(spec, environment, needs));
            previous = id;
        }

        if (GitHubGenerator.SlotPreviews(spec))
        {
            // A review app: the merge request gets a slot of the first environment's application, and loses it when it closes.
            var first = spec.Environments[0];
            const string Slot = "pr-$CI_MERGE_REQUEST_IID";
            const string Review = "review/$CI_MERGE_REQUEST_IID";
            var variables = new YMap { { "APP", first.ResourceName }, { "RESOURCE_GROUP", first.ResourceGroup }, { "SLOT", Slot } };
            var jvm = spec.Build.IsJvm && spec.Build.CustomCommands.Count == 0;
            root.Add("preview", new YMap
            {
                { "extends", ".azure" },
                { "stage", "deploy" },
                { "needs", new YSeq(lastBuild) },
                { "rules", new YSeq { new YMap { { "if", "$CI_PIPELINE_SOURCE == \"merge_request_event\"" } } } },
                { "environment", new YMap { { "name", Review }, { "url", "$PREVIEW_URL" }, { "on_stop", "stop-preview" }, { "auto_stop_in", "1 week" } } },
                { "variables", variables },
                {
                    "script", new YSeq(
                    [
                        "az webapp deployment slot list --resource-group \"$RESOURCE_GROUP\" --name \"$APP\" --query \"[].name\" --output tsv | grep -qx \"$SLOT\" || az webapp deployment slot create --resource-group \"$RESOURCE_GROUP\" --name \"$APP\" --slot \"$SLOT\" --configuration-source \"$APP\" --output none",
                        jvm
                            ? $"az webapp deploy --resource-group \"$RESOURCE_GROUP\" --name \"$APP\" --slot \"$SLOT\" --src-path {Commands.PackagePattern(spec, Commands.PackageFolder)} --type jar"
                            : Zip() + "\naz webapp deploy --resource-group \"$RESOURCE_GROUP\" --name \"$APP\" --slot \"$SLOT\" --src-path app.zip --type zip",
                        "echo \"PREVIEW_URL=https://$(az webapp show --resource-group \"$RESOURCE_GROUP\" --name \"$APP\" --slot \"$SLOT\" --query defaultHostName --output tsv)\" > preview.env",
                    ])
                },
                { "artifacts", new YMap { { "reports", new YMap { { "dotenv", "preview.env" } } } } },
            });
            root.Add("stop-preview", new YMap
            {
                { "extends", ".azure" },
                { "stage", "deploy" },
                { "needs", new YSeq() },
                { "rules", new YSeq { new YMap { { "if", "$CI_PIPELINE_SOURCE == \"merge_request_event\"" }, { "when", "manual" }, { "allow_failure", true } } } },
                { "environment", new YMap { { "name", Review }, { "action", "stop" } } },
                { "variables", new YMap { { "APP", first.ResourceName }, { "RESOURCE_GROUP", first.ResourceGroup }, { "SLOT", Slot }, { "GIT_STRATEGY", "none" } } },
                { "script", new YSeq(["az webapp deployment slot delete --resource-group \"$RESOURCE_GROUP\" --name \"$APP\" --slot \"$SLOT\""]) },
            });
        }

        if (spec.Deploy.RollbackPipeline && spec.IsServerApp)
        {
            // Optional jobs started by hand; the pipeline does not wait for them.
            foreach (var environment in spec.Environments)
            {
                var rollback = ServerJob(spec, environment, ServerDeploy.Script(spec, environment, Platform.GitLab, rollback: true));
                rollback.Add("stage", "rollback");
                rollback.Add("needs", new YSeq());
                AddVariables(rollback, [new("GIT_STRATEGY", "none")]);
                rollback.Add("environment", new YMap { { "name", environment.Name } });
                rollback.Add("resource_group", environment.Name);
                rollback.Add("rules", new YSeq
                {
                    new YMap
                    {
                        { "if", spec.Flow == Flow.Tag ? TagCondition(spec) : $"{NotMergeRequest} && $CI_COMMIT_BRANCH == \"{spec.BranchOf(environment)}\"" },
                        { "when", "manual" },
                        { "allow_failure", true },
                    },
                });
                if (spec.OnServerRunner && environment.Servers.Count > 0)
                {
                    rollback.Add("parallel", new YMap { { "matrix", new YSeq { new YMap { { "SERVER", new YSeq(environment.Servers) } } } } });
                }

                root.Add("rollback-" + environment.Name, rollback);
            }
        }

        if (spec.NotifyOnFailure)
        {
            root.Add("notify-failure", new YMap
            {
                { "stage", ".post" },
                { "image", "curlimages/curl:latest" },
                { "rules", new YSeq { new YMap { { "if", NotMergeRequest }, { "when", "on_failure" } } } },
                { "variables", new YMap { { "WEBHOOK", "$NOTIFY_WEBHOOK" }, { "TEXT", $"The pipeline of {spec.Name} failed: $CI_PIPELINE_URL" } } },
                { "script", new YSeq([Commands.Notify]) },
            });
        }

        var last = spec.Environments[^1];
        var lastRule = spec.Flow == Flow.Tag ? TagCondition(spec) : $"{NotMergeRequest} && $CI_COMMIT_BRANCH == \"{spec.BranchOf(last)}\"";
        if (spec.NotifyOnSuccess)
        {
            root.Add("notify-success", new YMap
            {
                { "stage", ".post" },
                { "image", "curlimages/curl:latest" },
                { "needs", new YSeq([JobId(last)]) },
                { "rules", new YSeq { new YMap { { "if", lastRule }, { "when", "on_success" } } } },
                { "variables", new YMap { { "WEBHOOK", "$NOTIFY_WEBHOOK" }, { "TEXT", $"{spec.Name} is deployed to {last.Name}: $CI_PIPELINE_URL" } } },
                { "script", new YSeq([Commands.Notify]) },
            });
        }

        if (spec.CreateRelease && spec.Flow == Flow.Tag)
        {
            root.Add("release", new YMap
            {
                { "stage", ".post" },
                { "image", "registry.gitlab.com/gitlab-org/release-cli:latest" },
                { "needs", new YSeq([JobId(last)]) },
                { "rules", new YSeq { new YMap { { "if", lastRule } } } },
                { "script", new YSeq(["echo \"Publishing the release $CI_COMMIT_TAG\""]) },
                { "release", new YMap { { "tag_name", "$CI_COMMIT_TAG" }, { "description", "Release $CI_COMMIT_TAG" } } },
            });
        }

        return root;
    }

    public static string JobId(EnvironmentSpec environment) => "deploy-" + environment.Name;

    private static YSeq WorkflowRules(PipelineSpec spec)
    {
        var rules = new YSeq();
        if (spec.BuildPullRequests)
        {
            rules.Add(new YMap { { "if", "$CI_PIPELINE_SOURCE == \"merge_request_event\"" } });
        }

        rules.Add(new YMap { { "if", BranchCondition(spec.DeployBranches()) } });
        if (spec.Flow == Flow.Tag)
        {
            rules.Add(new YMap { { "if", TagCondition(spec) } });
        }

        if (spec.SeveralApps)
        {
            // This file runs as a child pipeline, started by the job of the root .gitlab-ci.yml.
            rules.Insert(0, new YMap { { "if", "$CI_PIPELINE_SOURCE == \"parent_pipeline\"" } });
        }

        if (spec.ManualRun)
        {
            rules.Add(new YMap { { "if", "$CI_PIPELINE_SOURCE == \"web\"" } });
        }

        if (!string.IsNullOrWhiteSpace(spec.Schedule))
        {
            // GitLab keeps the schedule itself in the project (Build → Pipeline schedules); this lets its pipelines run.
            rules.Add(new YMap { { "if", "$CI_PIPELINE_SOURCE == \"schedule\"" } });
        }

        return rules;
    }

    /// <summary>v* becomes a tag that starts with v; a pattern without * is that tag exactly.</summary>
    private static string TagCondition(PipelineSpec spec) => spec.TagPattern.EndsWith('*')
        ? $"$CI_COMMIT_TAG =~ /^{spec.TagPattern[..^1].Replace(".", "\\.", StringComparison.Ordinal)}/"
        : $"$CI_COMMIT_TAG == \"{spec.TagPattern}\"";

    private static string BranchCondition(IEnumerable<string> branches) =>
        string.Join(" || ", branches.Select(branch => $"$CI_COMMIT_BRANCH == \"{branch}\""));

    private static YMap AzureTemplate() => new()
    {
        { "image", AzureCliImage },
        { "id_tokens", IdToken() },
        {
            "before_script", new YSeq(
            [
                "az login --service-principal --username \"$AZURE_CLIENT_ID\" --tenant \"$AZURE_TENANT_ID\" --federated-token \"$AZURE_JWT\" --output none",
                "az account set --subscription \"$AZURE_SUBSCRIPTION_ID\"",
            ])
        },
    };

    private static YMap IdToken() => new() { { "AZURE_JWT", new YMap { { "aud", "api://AzureADTokenExchange" } } } };

    private static List<(string Name, YMap Job)> BuildJobs(PipelineSpec spec)
    {
        var deploy = spec.Deploy;
        if (deploy.Target == Target.Terraform)
        {
            return [("check", TerraformJob(spec, "build", Commands.TerraformCheck(), withAzure: false))];
        }

        if (deploy.Target == Target.Bicep)
        {
            return [("check", new YMap
            {
                { "stage", "build" },
                { "image", AzureCliImage },
                { "script", new YSeq(["az bicep install", Commands.BicepCheck(spec)]) },
            })];
        }

        if (deploy.Target == Target.ArmTemplate)
        {
            return [("check", new YMap { { "stage", "build" }, { "image", CloudDeploy.AwsImage }, { "script", new YSeq([Commands.BicepCheck(spec)]) } })];
        }

        if (Infra.Check(spec) is { } check)
        {
            return [("check", new YMap { { "stage", "build" }, { "image", Infra.Image(spec) }, { "script", new YSeq([check]) } })];
        }

        var jobs = new List<(string, YMap)>();
        var steps = Commands.Build(spec).ToList();
        if (Feeds.ConfigureScript(spec, Platform.GitLab) is { } configure)
        {
            steps.Insert(0, new("Configure package feeds", configure));
        }

        if (Commands.ImagePreparation(spec) is { } prepare)
        {
            steps.Insert(0, new("Install the tools", prepare));
        }

        if (Services.Wait(spec, byName: true) is { } wait)
        {
            steps.Insert(0, new(Services.WaitName, wait));
        }

        var migrations = DeployExtras.BuildMigrations(spec);
        if (migrations is not null)
        {
            steps.Add(new(migrations.Name, migrations.Script));
        }

        if (steps.Count > 0)
        {
            // On Windows the runner's shell is PowerShell and there is no image; a step stops at its first error.
            var windows = spec.IsWindowsBuild;
            var job = new YMap
            {
                { "stage", "build" },
                { "image", windows || spec.Build.Agent == BuildAgent.SelfHostedMac ? null : spec.IsMacBuild ? CloudDeploy.MacImage : BuildImage(spec) },
                { "tags", BuildTags(spec) },
                { "variables", Variables([.. Feeds.BuildEnv(spec, Platform.GitLab), .. Services.Env(spec, byName: true)]) },
                { "services", ServiceList(spec) },
                {
                    "script", new YSeq(steps.Select(step => windows
                        ? $"# {step.Name}\n$ErrorActionPreference = 'Stop'\ncd $env:CI_PROJECT_DIR\n{step.Script}"
                        : $"# {step.Name}\ncd \"$CI_PROJECT_DIR\"\n{step.Script}"))
                },
            };
            if (PackageCache.Applies(spec))
            {
                var (key, value) = PackageCache.Variable(spec.Build.Stack, "$CI_PROJECT_DIR");
                AddVariables(job, [new(key, value)]);
                job.Add("cache", new YMap
                {
                    { "key", "packages" },
                    { "paths", new YSeq([PackageCache.Folder(spec.Build.Stack)]) },
                });
            }

            var paths = new YSeq();
            if (spec.UsesPackage)
            {
                paths.Add(Commands.PackageFolder);
            }

            if (migrations is not null)
            {
                paths.Add(DeployExtras.MigrationsFolder);
            }

            var artifacts = new YMap();
            if (spec.Build.PublishTestResults)
            {
                // Kept even when a test fails; Java results also fill the Tests tab.
                artifacts.Add("when", "always");
                if (spec.Build.WritesJUnit)
                {
                    artifacts.Add("reports", new YMap { { "junit", new YSeq([Commands.JUnitFiles(spec)]) } });
                }
                else
                {
                    paths.Add(Commands.TestResults);
                }
            }

            if (spec.Build.Sbom && Quality.Applies(spec))
            {
                paths.Add(Quality.Reports);
            }

            if (spec.Build.Coverage)
            {
                // GitLab shows the covered lines in merge requests.
                artifacts.Add("reports", new YMap { { "coverage_report", new YMap { { "coverage_format", "cobertura" }, { "path", Commands.TestResults + "/*/coverage.cobertura.xml" } } } });
            }

            if (paths.Count > 0)
            {
                artifacts.Add("paths", paths);
            }

            if (artifacts.Count > 0)
            {
                artifacts.Add("expire_in", "1 week");
                job.Add("artifacts", artifacts);
            }

            jobs.Add(("build", job));
        }

        if (spec.IsContainer && !spec.IsAzureContainer)
        {
            // Merge requests run the tests only; the image is built and pushed for the deploy branches.
            // AWS builds with Docker, which a GitLab job gets from the Docker-in-Docker service.
            var image = CloudJob(spec, new YSeq([CloudDeploy.BuildImage(spec, Sha)]), docker: spec.IsAws || spec.IsGenericRegistry);
            image.Add("stage", "build");
            image.Add("needs", new YSeq(jobs.Select(job => job.Item1)));
            image.Add("rules", new YSeq { new YMap { { "if", NotMergeRequest } } });
            AddVariables(image, CloudDeploy.Env(spec, null, Platform.GitLab));
            jobs.Add(("build-image", image));
        }

        if (spec.IsAzureContainer)
        {
            // Merge requests run the tests only; the image is built and pushed for the deploy branches.
            jobs.Add(("build-image", new YMap
            {
                { "stage", "build" },
                { "extends", ".azure" },
                { "needs", new YSeq(jobs.Select(job => job.Item1)) },
                { "rules", new YSeq { new YMap { { "if", NotMergeRequest } } } },
                { "variables", Variables(Feeds.DockerEnv(spec, Platform.GitLab)) },
                { "script", new YSeq([Commands.BuildImage(spec, Sha)]) },
            }));
        }

        return jobs;
    }

    private static YMap DeployJob(PipelineSpec spec, EnvironmentSpec environment, YSeq needs)
    {
        var deploy = spec.Deploy;
        YMap job;
        switch (deploy.Target)
        {
            case Target.AppService:
            {
                var slot = Slot(environment);
                var script = spec.Build.IsJvm && spec.Build.CustomCommands.Count == 0
                    ? new YSeq([$"az webapp deploy --resource-group {environment.ResourceGroup} --name {environment.ResourceName} --src-path {Commands.PackagePattern(spec, Commands.PackageFolder)} --type jar{slot}"])
                    : new YSeq([Zip(), $"az webapp deploy --resource-group {environment.ResourceGroup} --name {environment.ResourceName} --src-path app.zip --type zip{slot}"]);
                job = Azure(script);
                break;
            }

            case Target.FunctionApp:
                job = Azure(new YSeq(
                [
                    Zip(),
                    $"az functionapp deployment source config-zip --resource-group {environment.ResourceGroup} --name {environment.ResourceName} --src app.zip{Slot(environment)}",
                ]));
                break;
            case Target.StaticWebApp:
                job = new YMap
                {
                    { "image", "node:22" },
                    {
                        "script", new YSeq(
                        [
                            $"npx --yes @azure/static-web-apps-cli deploy {Commands.PackageFolder} --deployment-token \"$SWA_TOKEN\" --env production",
                        ])
                    },
                };
                break;
            case Target.ContainerApp:
                job = Azure(new YSeq([Commands.ContainerAppUpdate(spec, environment, Commands.Image(spec, Sha))]));
                AddVariables(job, DeployExtras.DeployEnv(spec, environment, Platform.GitLab));
                break;
            case Target.Aks:
                job = Azure(new YSeq([Commands.AksDeploy(spec, environment, Commands.Image(spec, Sha))]));
                break;
            case Target.Terraform when spec.NeedsAzure:
                job = TerraformJob(spec, "deploy", Commands.TerraformDeploy(spec, environment), withAzure: true);
                break;
            case Target.Bicep or Target.ArmTemplate:
                job = Azure(new YSeq([Commands.BicepDeploy(spec, environment, "$CI_PIPELINE_IID")]));
                break;
            case Target.WindowsService:
            case Target.Iis:
            case Target.ScheduledTask:
            case Target.LinuxService:
                // The runner cleans its folder when it fetches the repository, so out/app holds only this build's artifacts.
                job = ServerJob(spec, environment, ServerDeploy.Script(spec, environment, Platform.GitLab));
                break;
            case Target.AwsS3 or Target.AwsLambda or Target.AwsElasticBeanstalk or Target.AwsEcs
                or Target.GcpCloudRun or Target.GcpCloudFunctions or Target.GcpAppEngine or Target.GcpGke
                or Target.AwsEks or Target.Kubernetes or Target.ContainerRegistry
                or Target.CloudFormation or Target.AwsCdk or Target.Pulumi
                or Target.GooglePlay or Target.AppStore or Target.MicrosoftStore
                or Target.Terraform or Target.Netlify or Target.Vercel or Target.CloudflarePages or Target.FirebaseHosting or Target.AwsSam or Target.AwsAppRunner or Target.GitOps or Target.DigitalOcean or Target.Database or Target.Heroku or Target.ServiceFabric:
                job = CloudJob(spec, new YSeq([CloudDeploy.Deploy(spec, environment, Platform.GitLab, Sha)]), docker: deploy.Target == Target.Heroku);
                AddVariables(job, CloudDeploy.Env(spec, environment, Platform.GitLab));
                break;
            case Target.Package:
            {
                var publish = Commands.PublishPackage(spec, Platform.GitLab, Commands.PackageFolder);
                job = new YMap { { "image", BuildImage(spec) }, { "script", new YSeq([publish.Script]) } };
                AddVariables(job, publish.Env);
                break;
            }

            default:
            {
                var script = new YSeq([Own(spec, Commands.DeployLines(spec, environment))]);
                job = spec.OnServerRunner ? Server(environment, script)
                    : spec.NeedsAzure ? Azure(script)
                    : new YMap { { "image", "ubuntu:24.04" }, { "script", script } };
                AddVariables(job, DeployExtras.DeployEnv(spec, environment, Platform.GitLab));
                break;
            }
        }

        // Before the deploy command, in order: the person's own commands, the database, the settings.
        var steps = (YSeq)job["script"]!;

        // On the image that reaches the servers over SSH, the first line installs the tools the next ones use.
        var at = spec.IsRemote && !spec.UsesPowerShell ? 1 : 0;
        if (environment.BeforeDeploy.Count > 0)
        {
            steps.Insert(at++, new YScalar(Own(spec, environment.BeforeDeploy), Raw: false));
        }

        foreach (var extra in DeployExtras.Before(spec, environment, Platform.GitLab))
        {
            steps.Insert(at++, new YScalar($"# {extra.Name}\n" + (spec.UsesPowerShell && !extra.Script.StartsWith("$ErrorActionPreference", StringComparison.Ordinal) ? "$ErrorActionPreference = 'Stop'\n" : "") + extra.Script, Raw: false));
            AddVariables(job, extra.Env);
        }

        // Several servers: the same job once per runner tag; the resource group lets one run at a time.
        if (spec.OnServerRunner && environment.Servers.Count > 0)
        {
            job.Add("parallel", new YMap { { "matrix", new YSeq { new YMap { { "SERVER", new YSeq(environment.Servers) } } } } });
        }

        if (spec.OnServerRunner && Strategies.ServerPause(spec, environment) is { } pause && Strategies.FirstServer(spec, environment) is { } first)
        {
            steps.Add(spec.UsesPowerShell ? $"if ($env:SERVER -eq '{first}') {{ {pause} }}" : $"if [ \"$SERVER\" = \"{first}\" ]; then {pause}; fi");
        }

        if (Strategies.SlotSwap(spec, environment) is { } swap)
        {
            steps.Add("# Move the traffic to the new version\n" + swap);
        }

        if (Commands.After(environment).Count > 0)
        {
            steps.Add(Own(spec, Commands.After(environment)));
        }

        if (Commands.HasOwnCommands(spec, environment))
        {
            AddVariables(job, [new("DEPLOY_ENVIRONMENT", environment.Name)]);
        }

        var rule = new YMap
        {
            { "if", spec.Flow == Flow.Tag ? TagCondition(spec) : $"{NotMergeRequest} && $CI_COMMIT_BRANCH == \"{spec.BranchOf(environment)}\"" },
            { "when", environment.RequireApproval ? "manual" : "on_success" },
        };

        var result = new YMap { { "stage", "deploy" } };
        foreach (var (key, value) in job)
        {
            if (key != "stage")
            {
                result.Add(key, value);
            }
        }

        result.Add("needs", needs);
        result.Add("environment", new YMap { { "name", environment.Name } });

        // One deployment at a time per environment.
        result.Add("resource_group", environment.Name);
        result.Add("rules", new YSeq { rule });

        // A manual job blocks the jobs after it until someone runs it.
        result.Add("allow_failure", environment.RequireApproval ? (YNode)false : null);
        return result;
    }

    private static YMap TerraformJob(PipelineSpec spec, string stage, string script, bool withAzure)
    {
        var job = new YMap
        {
            { "stage", stage },
            { "image", new YMap { { "name", $"hashicorp/terraform:{spec.Deploy.TerraformVersion}" }, { "entrypoint", new YSeq([""]) } } },
        };
        if (withAzure)
        {
            job.Add("id_tokens", IdToken());
            job.Add("variables", new YMap
            {
                { "ARM_CLIENT_ID", "$AZURE_CLIENT_ID" },
                { "ARM_TENANT_ID", "$AZURE_TENANT_ID" },
                { "ARM_SUBSCRIPTION_ID", "$AZURE_SUBSCRIPTION_ID" },
                { "ARM_OIDC_TOKEN", "$AZURE_JWT" },
                { "ARM_USE_OIDC", "true" },
            });
        }

        job.Add("script", new YSeq([$"cd {spec.Deploy.InfraDirectory}\n{script}"]));
        return job;
    }

    /// <summary>
    /// Job variables; one that only names the CI/CD variable of the same name ($FEED_X_TOKEN) is already there and is
    /// not repeated.
    /// </summary>
    /// <summary>The services of the build job; the tests reach each one by its alias.</summary>
    private static YSeq? ServiceList(PipelineSpec spec)
    {
        var list = new YSeq();
        foreach (var service in Services.All(spec))
        {
            list.Add(new YMap { { "name", service.Image }, { "alias", service.Name }, { "variables", Variables(service.Env) } });
        }

        return list.Count == 0 ? null : list;
    }

    private static YMap? Variables(IReadOnlyList<KeyValuePair<string, string>> values)
    {
        var variables = new YMap();
        foreach (var (key, value) in values.Where(pair => pair.Value != "$" + pair.Key))
        {
            variables.Add(key, new YScalar(value, Raw: false));
        }

        return variables.Count > 0 ? variables : null;
    }

    /// <summary>The person's commands; on a server they stop at the first PowerShell error like every other step.</summary>
    private static string Own(PipelineSpec spec, IEnumerable<string> commands) =>
        (spec.UsesPowerShell ? "$ErrorActionPreference = 'Stop'\n" : "") + Commands.Lines(commands);

    /// <summary>
    /// The job that deploys an application to servers: on their own runners, or from a hosted runner that reaches
    /// them over WinRM (GitLab's Windows runners) or SSH (an image with the SSH client and rsync added).
    /// </summary>
    private static YMap ServerJob(PipelineSpec spec, EnvironmentSpec environment, string script)
    {
        YMap job;
        if (spec.OnServerRunner)
        {
            job = Server(environment, new YSeq([script]));
        }
        else if (spec.UsesPowerShell)
        {
            job = new YMap { { "tags", new YSeq(["saas-windows-medium-amd64"]) }, { "script", new YSeq([script]) } };
        }
        else
        {
            job = new YMap
            {
                { "image", "ubuntu:24.04" },
                { "script", new YSeq(["apt-get update -qq && apt-get install -y -qq openssh-client rsync python3 curl > /dev/null", script]) },
            };
        }

        AddVariables(job, DeployExtras.DeployEnv(spec, environment, Platform.GitLab));
        return job;
    }

    /// <summary>A job for the runners with this environment's tag, installed on its servers (PowerShell shell).</summary>
    private static YMap Server(EnvironmentSpec environment, YSeq script) => new()
    {
        { "tags", new YSeq([environment.Servers.Count > 0 ? "$SERVER" : environment.ServerLabel!]) },
        { "script", script },
    };

    /// <summary>
    /// Adds variables to a job. A value that only names the CI/CD variable of the same name ($DB_CONNECTION) is
    /// already there, so it is not repeated (it would refer to itself).
    /// </summary>
    private static void AddVariables(YMap job, IReadOnlyList<KeyValuePair<string, string>> values)
    {
        foreach (var (key, value) in values.Where(pair => pair.Value != "$" + pair.Key))
        {
            if (job["variables"] is not YMap variables)
            {
                variables = new YMap();
                job.Add("variables", variables);
            }

            if (variables[key] is null)
            {
                variables.Add(key, new YScalar(value, Raw: false));
            }
        }
    }

    private static YSeq? BuildTags(PipelineSpec spec) => spec.Build.Agent switch
    {
        // GitLab's own hosted Windows runners.
        BuildAgent.HostedWindows => new YSeq(["saas-windows-medium-amd64"]),
        BuildAgent.SelfHostedLinux or BuildAgent.SelfHostedWindows or BuildAgent.SelfHostedMac => new YSeq([spec.Build.AgentLabel!]),
        BuildAgent.HostedMac => new YSeq([CloudDeploy.MacTag]),
        _ => null,
    };

    /// <summary>A job signed in to AWS or Google Cloud with the job's own ID token (no stored keys).</summary>
    private static YMap CloudJob(PipelineSpec spec, YSeq script, bool docker)
    {
        if (spec.IsGenericRegistry || spec.IsStore || spec.IsTokenHost || spec.Deploy.Target == Target.Database)
        {
            // Docker, kubectl and the stores' tools sign in with the secrets of their own steps: no cloud token to exchange.
            return new YMap
            {
                { "image", docker ? "docker:27" : spec.DeploysOnMac && spec.Build.Agent == BuildAgent.SelfHostedMac ? null : CloudDeploy.GitLabImage(spec) },
                { "tags", spec.DeploysOnMac ? BuildTags(spec) : null },
                { "services", docker ? new YSeq(["docker:27-dind"]) : null },
                { "variables", docker ? new YMap { { "DOCKER_TLS_CERTDIR", "/certs" } } : null },
                { "script", script },
            };
        }

        if (spec.NeedsAzure)
        {
            // Pulumi on Azure signs in by itself with the job's token, as Terraform does.
            return new YMap
            {
                { "image", Infra.Image(spec) },
                { "id_tokens", IdToken() },
                {
                    "variables", new YMap
                    {
                        { "ARM_CLIENT_ID", "$AZURE_CLIENT_ID" },
                        { "ARM_TENANT_ID", "$AZURE_TENANT_ID" },
                        { "ARM_SUBSCRIPTION_ID", "$AZURE_SUBSCRIPTION_ID" },
                        { "ARM_OIDC_TOKEN", "$AZURE_JWT" },
                        { "ARM_USE_OIDC", "true" },
                    }
                },
                { "script", script },
            };
        }

        var (token, audience) = CloudDeploy.GitLabToken(spec);
        var job = new YMap
        {
            { "image", docker ? "docker:27" : CloudDeploy.GitLabImage(spec) },
            { "services", docker ? new YSeq(["docker:27-dind"]) : null },
            { "variables", docker ? new YMap { { "DOCKER_TLS_CERTDIR", "/certs" } } : null },
            { "id_tokens", new YMap { { token, new YMap { { "aud", audience } } } } },
            { "before_script", new YSeq(CloudDeploy.GitLabSignIn(spec, docker)) },
            { "script", script },
        };
        return job;
    }

    private static YMap Azure(YSeq script) => new() { { "extends", ".azure" }, { "script", script } };

    // The azure-cli image has Python, whose zipfile module zips the folder contents without a zip tool.
    private static string Zip() => $"python3 -m zipfile -c app.zip {Commands.PackageFolder}/.";

    private static string Slot(EnvironmentSpec environment) => string.IsNullOrWhiteSpace(environment.Slot) ? "" : $" --slot {environment.Slot}";

    private static string BuildImage(PipelineSpec spec) => Commands.BuildImage(spec);

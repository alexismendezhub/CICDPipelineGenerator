namespace CICDPipelineGenerator.Domain;

/// <summary>
/// azure-pipelines.yml: a Build stage and one stage per environment with a deployment job. Each environment signs in
/// with its own Azure Resource Manager service connection (workload identity federation); approvals are checks on
/// the Azure DevOps environment of the same name.
/// </summary>
public static class AzureDevOpsGenerator
{
    public const string Path = "azure-pipelines.yml";

    /// <summary>With several applications in the repository, each one has its own file.</summary>
    public static string PathFor(PipelineSpec spec) => spec.SeveralApps ? $"azure-pipelines-{spec.Name}.yml" : Path;
    private const string Sha = "$(Build.SourceVersion)";
    private const string Artifact = "$(Pipeline.Workspace)/app";

    public static GeneratedFile Generate(PipelineSpec spec) => new(PathFor(spec), YamlWriter.Write(Root(spec),
    [
        $"Generated by CI/CD Pipeline Generator for {spec.Name}.",
        "Before the first run, follow SETUP.md: service connections, environments and approvals.",
    ]));

    internal static YMap Root(PipelineSpec spec)
    {
        var root = new YMap
        {
            { "name", "$(Date:yyyyMMdd)$(Rev:.r)" },
            { "trigger", Trigger(spec) },
            { "pr", spec.BuildPullRequests ? new YMap { { "branches", new YMap { { "include", new YSeq(spec.DeployBranches()) } } } } : "none" },
            { "schedules", Schedules(spec) },
            { "pool", new YMap { { "vmImage", "ubuntu-latest" } } },
            { "resources", ServiceContainers(spec) },
            { "stages", Stages(spec) },
        };
        return root;
    }

    private static YSeq? Schedules(PipelineSpec spec) => string.IsNullOrWhiteSpace(spec.Schedule)
        ? null
        : new YSeq
        {
            new YMap
            {
                { "cron", new YScalar(spec.Schedule, Raw: false) },
                { "displayName", "Scheduled run" },
                { "branches", new YMap { { "include", new YSeq(spec.DeployBranches()) } } },
                // Run even when nothing changed since the last run.
                { "always", true },
            },
        };

    private static YMap Trigger(PipelineSpec spec)
    {
        if (spec.Flow == Flow.Tag)
        {
            return new YMap { { "tags", new YMap { { "include", new YSeq([spec.TagPattern]) } } } };
        }

        var trigger = new YMap { { "branches", new YMap { { "include", new YSeq(spec.DeployBranches()) } } } };
        if (spec.PathFilters.Count > 0)
        {
            trigger.Add("paths", new YMap { { "include", new YSeq(spec.PathFilters) } });
        }

        return trigger;
    }

    public static string RollbackPathFor(PipelineSpec spec) =>
        spec.SeveralApps ? $"azure-pipelines-rollback-{spec.Name}.yml" : "azure-pipelines-rollback.yml";

    /// <summary>A pipeline started by hand that puts the previous version of the chosen environment back on its servers.</summary>
    public static GeneratedFile Rollback(PipelineSpec spec)
    {
        var stages = new YSeq();
        foreach (var environment in spec.Environments)
        {
            var back = Shell(spec, "Put the previous version back", ServerDeploy.Script(spec, environment, Platform.AzureDevOps, rollback: true));
            back.Add("env", Env(RemoteDeploy.Env(spec, environment, Platform.AzureDevOps)));
            var steps = new YSeq { back };
            stages.Add(new YMap
            {
                { "stage", "Rollback_" + environment.Name.Replace('-', '_') },
                { "displayName", $"Roll back {environment.Name}" },
                { "dependsOn", new YSeq() },
                { "condition", $"eq('${{{{ parameters.environment }}}}', '{environment.Name}')" },
                {
                    "jobs", new YSeq
                    {
                        new YMap
                        {
                            { "deployment", "Rollback" },
                            { "displayName", $"Roll back {environment.Name}" },
                            { "environment", spec.OnServerRunner ? new YMap { { "name", environment.Name }, { "resourceType", "VirtualMachine" }, { "tags", environment.ServerLabel } } : new YScalar(environment.Name, Raw: false) },
                            { "pool", spec.IsRemote ? new YMap { { "vmImage", spec.UsesPowerShell ? "windows-latest" : "ubuntu-latest" } } : null },
                            { "strategy", spec.OnServerRunner
                                ? new YMap { { "rolling", new YMap { { "maxParallel", "1" }, { "deploy", new YMap { { "steps", steps } } } } } }
                                : new YMap { { "runOnce", new YMap { { "deploy", new YMap { { "steps", steps } } } } } } },
                        },
                    }
                },
            });
        }

        var root = new YMap
        {
            { "name", "$(Date:yyyyMMdd)$(Rev:.r)" },
            { "trigger", "none" },
            { "pr", "none" },
            {
                "parameters", new YSeq
                {
                    new YMap
                    {
                        { "name", "environment" },
                        { "displayName", "The environment that goes back to its previous version" },
                        { "type", "string" },
                        { "values", new YSeq(spec.Environments.Select(environment => environment.Name)) },
                    },
                }
            },
            { "stages", stages },
        };
        return new(RollbackPathFor(spec), YamlWriter.Write(root, [$"Generated by CI/CD Pipeline Generator for {spec.Name}.", "Create a pipeline from this file and run it by hand to put the previous version back."]));
    }

    public static string StageId(EnvironmentSpec environment) => "Deploy_" + environment.Name.Replace('-', '_');

    private static YSeq Stages(PipelineSpec spec)
    {
        var stages = new YSeq { BuildStage(spec) };
        var previous = "Build";
        foreach (var environment in spec.Environments)
        {
            var id = StageId(environment);
            stages.Add(new YMap
            {
                { "stage", id },
                { "displayName", $"Deploy to {environment.Name}" },
                { "dependsOn", spec.Promotes ? previous : "Build" },
                {
                    "condition",
                    spec.Flow == Flow.Tag
                        ? "and(succeeded(), ne(variables['Build.Reason'], 'PullRequest'), startsWith(variables['Build.SourceBranch'], 'refs/tags/'))"
                        : $"and(succeeded(), ne(variables['Build.Reason'], 'PullRequest'), eq(variables['Build.SourceBranch'], 'refs/heads/{spec.BranchOf(environment)}'))"
                },
                { "jobs", new YSeq { DeployJob(spec, environment) } },
            });
            previous = id;
        }

        if (spec.NotifyOnFailure)
        {
            var notify = Script("Post to the webhook", Commands.Notify, new YMap
            {
                { "WEBHOOK", "$(NOTIFY_WEBHOOK)" },
                { "TEXT", $"The pipeline of {spec.Name} failed: $(System.CollectionUri)$(System.TeamProject)/_build/results?buildId=$(Build.BuildId)" },
            });
            stages.Add(new YMap
            {
                { "stage", "Notify" },
                { "displayName", "Tell the team it failed" },
                { "dependsOn", new YSeq(spec.Environments.Select(StageId).Prepend("Build")) },
                { "condition", "and(failed(), ne(variables['Build.Reason'], 'PullRequest'))" },
                { "jobs", new YSeq { new YMap { { "job", "Notify" }, { "steps", new YSeq { notify } } } } },
            });
        }

        if (spec.NotifyOnSuccess)
        {
            var done = Script("Post to the webhook", Commands.Notify, new YMap
            {
                { "WEBHOOK", "$(NOTIFY_WEBHOOK)" },
                { "TEXT", $"{spec.Name} is deployed to {spec.Environments[^1].Name}: $(System.CollectionUri)$(System.TeamProject)/_build/results?buildId=$(Build.BuildId)" },
            });
            stages.Add(new YMap
            {
                { "stage", "NotifySuccess" },
                { "displayName", "Tell the team it is deployed" },
                { "dependsOn", new YSeq(spec.Environments.Select(StageId)) },
                { "condition", "and(succeeded(), ne(variables['Build.Reason'], 'PullRequest'))" },
                { "jobs", new YSeq { new YMap { { "job", "NotifySuccess" }, { "steps", new YSeq { done } } } } },
            });
        }

        return stages;
    }

    private static YMap BuildStage(PipelineSpec spec)
    {
        var steps = new YSeq { new YMap { { "checkout", "self" } } };
        var deploy = spec.Deploy;
        if (deploy.Target == Target.Terraform)
        {
            steps.Add(Script("Check the Terraform code", $"{Commands.InstallTerraform(spec)}\ncd {deploy.InfraDirectory}\n{Commands.TerraformCheck()}"));
        }
        else if (deploy.Target is Target.Bicep or Target.ArmTemplate)
        {
            steps.Add(Script(deploy.Target == Target.Bicep ? "Check the Bicep code" : "Check the template", Commands.BicepCheck(spec)));
        }
        else if (Infra.Check(spec) is { } check)
        {
            steps.Add(Script("Check the infrastructure code", check));
        }
        else
        {
            if (spec.Build.CustomCommands.Count == 0 && spec.Build.Stack is not (Stack.None or Stack.DotNetFramework or Stack.Ios or Stack.Msix or Stack.Cpp or Stack.Swift))
            {
                steps.Add(SetupTool(spec));
            }

            if (PackageCache.Applies(spec))
            {
                var name = PackageCache.Name(spec.Build.Stack);
                steps.Add(Task("Cache@2", "Keep the packages between runs", new YMap
                {
                    { "key", $"{name} | \"$(Agent.OS)\" | {PackageCache.KeyFiles(spec)}" },
                    { "restoreKeys", $"{name} | \"$(Agent.OS)\"" },
                    { "path", $"$(Pipeline.Workspace)/{PackageCache.Folder(spec.Build.Stack)}" },
                }));
            }

            var feedEnv = FeedEnv(spec);
            if (Services.Wait(spec, byName: false) is { } wait)
            {
                steps.Add(Script(Services.WaitName, wait));
            }

            if (Feeds.ConfigureScript(spec, Platform.AzureDevOps) is { } configure)
            {
                steps.Add(BuildStep(spec, "Configure package feeds", configure, FeedEnv(spec, npmOnly: true)));
            }

            var feeds = spec.Build.PackageFeeds.Where(feed => Feeds.UsesBuildIdentity(feed, Platform.AzureDevOps)).ToList();
            if (feeds.Any(feed => feed.Type == FeedType.NuGet))
            {
                // The build identity signs in to the organization's Azure Artifacts feeds; it needs Feed Reader on each one.
                steps.Add(new YMap { { "task", "NuGetAuthenticate@1" }, { "displayName", "Sign in to Azure Artifacts (NuGet)" } });
            }

            if (feeds.Any(feed => feed.Type == FeedType.Npm))
            {
                steps.Add(Task("npmAuthenticate@0", "Sign in to Azure Artifacts (npm)", new YMap
                {
                    { "workingFile", Commands.Join(spec.Build.WorkingDirectory, ".npmrc") },
                }));
            }

            foreach (var step in Commands.Build(spec))
            {
                steps.Add(BuildStep(spec, step.Name, step.Script, feedEnv));
            }

            if (spec.Build.PublishTestResults)
            {
                var java = spec.Build.WritesJUnit;
                var results = Task("PublishTestResults@2", "Publish the test results", new YMap
                {
                    { "testResultsFormat", java ? "JUnit" : "VSTest" },
                    { "testResultsFiles", java ? Commands.JUnitFiles(spec) : "**/*.trx" },
                    { "searchFolder", java ? "$(System.DefaultWorkingDirectory)" : "$(System.DefaultWorkingDirectory)/" + Commands.TestResults },
                });
                results.Add("condition", "succeededOrFailed()");
                steps.Add(results);
            }

            if (spec.Build.Coverage)
            {
                // Version 1 is the one whose inputs the published schema describes.
                var coverage = Task("PublishCodeCoverageResults@1", "Publish the code coverage", new YMap
                {
                    { "codeCoverageTool", "Cobertura" },
                    { "summaryFileLocation", "$(System.DefaultWorkingDirectory)/" + Commands.TestResults + "/**/coverage.cobertura.xml" },
                });
                coverage.Add("condition", "succeededOrFailed()");
                steps.Add(coverage);
            }

            if (spec.Build.Sbom && Quality.Applies(spec))
            {
                steps.Add(Publish("Keep the list of components", Quality.Reports, "reports"));
            }

            if (spec.UsesPackage)
            {
                steps.Add(Publish("Keep the package", Commands.PackageFolder, "app"));
            }

            if (DeployExtras.BuildMigrations(spec) is { } migrations)
            {
                steps.Add(BuildStep(spec, migrations.Name, migrations.Script, feedEnv));
                steps.Add(Publish("Keep the database migrations", DeployExtras.MigrationsFolder, "migrations"));
            }

            if (spec.IsContainer && !spec.IsAzureContainer && !spec.Build.TestsOnly)
            {
                // The image is built with the first environment's credentials.
                var cloudImage = Script("Build and push the image", CloudDeploy.AzureDevOpsSignIn(spec) + CloudDeploy.BuildImage(spec, Sha), Env(CloudDeploy.Env(spec, null, Platform.AzureDevOps)));
                cloudImage.Add("condition", "and(succeeded(), ne(variables['Build.Reason'], 'PullRequest'))");
                steps.Add(cloudImage);
            }

            if (spec.IsAzureContainer && !spec.Build.TestsOnly)
            {
                // The image is built with the first environment's connection, which needs AcrPush on the registry.
                var image = AzureCli("Build and push the image", spec.Environments[0].ServiceConnection!, Commands.BuildImage(spec, Sha));
                image.Add("condition", "and(succeeded(), ne(variables['Build.Reason'], 'PullRequest'))");
                image.Add("env", Env(Feeds.DockerEnv(spec, Platform.AzureDevOps)));
                steps.Add(image);
            }
        }

        var jobs = new YSeq
        {
            new YMap
            {
                { "job", spec.Build.TestsOnly ? Services.Id(spec.Build.EffectiveVersion, '_') : "Build" },
                { "displayName", spec.Build.TestsOnly ? Services.Name(spec.Build.EffectiveVersion) : null },
                { "pool", spec.IsInfrastructure ? null : BuildPool(spec) },
                { "variables", JobVariables(spec) },
                { "services", JobServices(spec) },
                { "steps", steps },
            },
        };
        foreach (var (_, other) in Services.Versions(spec))
        {
            // The stage ends well only when the tests pass with every version.
            jobs.Add(((YSeq)BuildStage(other)["jobs"]!).First());
        }

        return new YMap
        {
            { "stage", "Build" },
            { "displayName", spec.IsInfrastructure ? "Check" : "Build and test" },
            { "jobs", jobs },
        };
    }

    /// <summary>The containers of the services, named once for the whole file.</summary>
    private static YMap? ServiceContainers(PipelineSpec spec)
    {
        var containers = new YSeq();
        foreach (var service in Services.All(spec))
        {
            containers.Add(new YMap
            {
                { "container", service.Name },
                { "image", service.Image },
                { "env", Env(service.Env) },
                { "ports", new YSeq([$"{service.Port}:{service.Port}"]) },
            });
        }

        return containers.Count == 0 ? null : new YMap { { "containers", containers } };
    }

    private static YMap? JobVariables(PipelineSpec spec)
    {
        var variables = CacheVariables(spec) ?? [];
        foreach (var (key, value) in Services.Env(spec, byName: false))
        {
            variables.Add(key, value);
        }

        return variables.Count == 0 ? null : variables;
    }

    private static YMap? JobServices(PipelineSpec spec)
    {
        var services = new YMap();
        foreach (var service in Services.All(spec))
        {
            services.Add(service.Name, service.Name);
        }

        return services.Count == 0 ? null : services;
    }

    private static YMap DeployJob(PipelineSpec spec, EnvironmentSpec environment)
    {
        var deploy = spec.Deploy;
        var connection = environment.ServiceConnection ?? "";
        var steps = new YSeq();
        var deployEnv = DeployExtras.DeployEnv(spec, environment, Platform.AzureDevOps);
        switch (deploy.Target)
        {
            case Target.AppService:
            case Target.FunctionApp:
            {
                steps.Add(Download());
                var appService = deploy.Target == Target.AppService;
                var inputs = new YMap
                {
                    // AzureFunctionApp@2 names the connection input connectedServiceNameARM.
                    { appService ? "azureSubscription" : "connectedServiceNameARM", connection },
                    { "appType", (appService ? "webApp" : "functionApp") + (deploy.Os == HostOs.Linux ? "Linux" : "") },
                    { "appName", environment.ResourceName },
                    { "package", Commands.PackagePattern(spec, Artifact) },
                };
                if (!string.IsNullOrWhiteSpace(environment.Slot))
                {
                    inputs.Add("deployToSlotOrASE", true);
                    inputs.Add("resourceGroupName", environment.ResourceGroup);
                    inputs.Add("slotName", environment.Slot);
                }

                steps.Add(new YMap
                {
                    { "task", appService ? "AzureWebApp@1" : "AzureFunctionApp@2" },
                    { "displayName", $"Deploy to {environment.ResourceName}" },
                    { "inputs", inputs },
                });
                break;
            }

            case Target.StaticWebApp:
                steps.Add(Download());
                steps.Add(new YMap
                {
                    { "task", "AzureStaticWebApp@0" },
                    { "displayName", $"Deploy to {environment.ResourceName}" },
                    {
                        "inputs", new YMap
                        {
                            { "workingDirectory", "$(Pipeline.Workspace)" },
                            { "app_location", "app" },
                            { "skip_app_build", true },
                            { "skip_api_build", true },
                            { "azure_static_web_apps_api_token", $"$({SwaTokenVariable(environment)})" },
                        }
                    },
                });
                break;
            case Target.ContainerApp:
            {
                var update = AzureCli($"Deploy to {environment.ResourceName}", connection, Commands.ContainerAppUpdate(spec, environment, Commands.Image(spec, Sha)));
                update.Add("env", Env(deployEnv));
                steps.Add(update);
                break;
            }

            case Target.Aks:
                steps.Add(new YMap { { "checkout", "self" } });
                steps.Add(AzureCli($"Deploy to {environment.ResourceName}", connection, Commands.AksDeploy(spec, environment, Commands.Image(spec, Sha))));
                break;
            case Target.Terraform when spec.NeedsAzure:
            {
                steps.Add(new YMap { { "checkout", "self" } });

                // addSpnToEnvironment hands the connection's federated token to the script, so Terraform signs in without a secret.
                var script = string.Join('\n',
                [
                    Commands.InstallTerraform(spec),
                    "export ARM_CLIENT_ID=\"$servicePrincipalId\"",
                    "export ARM_TENANT_ID=\"$tenantId\"",
                    "export ARM_OIDC_TOKEN=\"$idToken\"",
                    "export ARM_USE_OIDC=true",
                    "export ARM_SUBSCRIPTION_ID=\"$(az account show --query id -o tsv)\"",
                    $"cd {deploy.InfraDirectory}",
                    Commands.TerraformDeploy(spec, environment),
                ]);
                var task = AzureCli(deploy.Preview ? "Plan and apply" : "Apply", connection, script);
                ((YMap)task["inputs"]!).Add("addSpnToEnvironment", true);
                steps.Add(task);
                break;
            }

            case Target.Bicep or Target.ArmTemplate:
                steps.Add(new YMap { { "checkout", "self" } });
                steps.Add(AzureCli(deploy.Preview ? "Preview and deploy" : "Deploy", connection, Commands.BicepDeploy(spec, environment, "$(Build.BuildId)")));
                break;
            case Target.WindowsService:
            case Target.Iis:
            case Target.ScheduledTask:
            case Target.LinuxService:
            {
                steps.Add(Download());
                var server = Shell(spec, $"Deploy to {environment.ResourceName} on the {environment.Name} servers", ServerDeploy.Script(spec, environment, Platform.AzureDevOps));
                server.Add("env", Env(deployEnv));
                steps.Add(server);
                break;
            }

            case Target.AwsS3 or Target.AwsLambda or Target.AwsElasticBeanstalk or Target.AwsEcs
                or Target.GcpCloudRun or Target.GcpCloudFunctions or Target.GcpAppEngine or Target.GcpGke
                or Target.AwsEks or Target.Kubernetes or Target.ContainerRegistry
                or Target.CloudFormation or Target.AwsCdk or Target.Pulumi
                or Target.GooglePlay or Target.AppStore or Target.MicrosoftStore
                or Target.Terraform or Target.Netlify or Target.Vercel or Target.CloudflarePages or Target.FirebaseHosting or Target.AwsSam or Target.AwsAppRunner or Target.GitOps or Target.DigitalOcean or Target.Database or Target.Heroku or Target.ServiceFabric:
            {
                if (CloudDeploy.NeedsRepository(spec))
                {
                    steps.Add(new YMap { { "checkout", "self" } });
                }

                if (spec.UsesPackage)
                {
                    steps.Add(Download());
                }

                if (spec.NeedsAzure)
                {
                    // Pulumi on Azure signs in by itself with the connection's federated token, as Terraform does.
                    var pulumi = AzureCli($"Deploy to {environment.ResourceName ?? environment.Name}", connection, string.Join('\n',
                    [
                        "export ARM_CLIENT_ID=\"$servicePrincipalId\"",
                        "export ARM_TENANT_ID=\"$tenantId\"",
                        "export ARM_OIDC_TOKEN=\"$idToken\"",
                        "export ARM_USE_OIDC=true",
                        "export ARM_SUBSCRIPTION_ID=\"`az account show --query id -o tsv`\"",
                        CloudDeploy.Deploy(spec, environment, Platform.AzureDevOps, Sha),
                    ]));
                    ((YMap)pulumi["inputs"]!).Add("addSpnToEnvironment", true);
                    pulumi.Add("env", Env(CloudDeploy.Env(spec, environment, Platform.AzureDevOps)));
                    steps.Add(pulumi);
                    break;
                }

                steps.Add(Script($"Deploy to {environment.ResourceName ?? environment.Name}", CloudDeploy.AzureDevOpsSignIn(spec) + CloudDeploy.Deploy(spec, environment, Platform.AzureDevOps, Sha), Env(CloudDeploy.Env(spec, environment, Platform.AzureDevOps))));
                break;
            }

            case Target.Package:
            {
                steps.Add(Download());
                var publish = Commands.PublishPackage(spec, Platform.AzureDevOps, "$PIPELINE_WORKSPACE/app");
                steps.Add(Script(publish.Name, publish.Script, Env(publish.Env)));
                break;
            }

            case Target.Script or Target.ApiManagement or Target.LogicApp or Target.DataFactory:
                steps.Add(new YMap { { "checkout", "self" } });
                if (spec.UsesPackage)
                {
                    steps.Add(Download());
                }

            {
                var own = Own(spec, connection, "Deploy", Commands.Lines(Commands.DeployLines(spec, environment)));
                own.Add("env", Env(deployEnv));
                steps.Add(own);
                break;
            }
        }

        // Before the deploy step, in order: the person's own commands, the database, the settings.
        var before = new List<YMap>();
        if (environment.BeforeDeploy.Count > 0)
        {
            before.Add(Own(spec, connection, "Before the deploy", Commands.Lines(environment.BeforeDeploy)));
        }

        foreach (var extra in DeployExtras.Before(spec, environment, Platform.AzureDevOps))
        {
            var step = spec.UsesPowerShell ? PowerShell(extra.Name, extra.Script)
                : extra.UsesAzure ? AzureCli(extra.Name, connection, extra.Script)
                : Script(extra.Name, extra.Script);
            step.Add("env", Env(extra.Env));
            before.Add(step);
        }

        var at = steps.Count - 1;
        foreach (var step in before)
        {
            steps.Insert(at++, step);
        }

        if ((deploy.Migrations == MigrationKind.SqlScripts || Commands.TestsAfter(environment)) && !steps.Any(step => step is YMap map && map["checkout"] is not null))
        {
            steps.Insert(0, new YMap { { "checkout", "self" } });
        }

        if (deploy.Migrations == MigrationKind.EfCoreBundle)
        {
            steps.Insert(0, new YMap { { "download", "current" }, { "artifact", "migrations" } });
        }

        if (Strategies.SlotSwap(spec, environment) is { } swap)
        {
            steps.Add(AzureCli($"Move the traffic to the new version ({environment.Slot} to production)", connection, swap));
        }

        if (Commands.After(environment).Count > 0)
        {
            steps.Add(Own(spec, connection, "After the deploy", Commands.Lines(Commands.After(environment))));
        }

        // On servers the job runs on the environment's virtual machines with this tag, through the agent installed there.
        YNode target = spec.OnServerRunner
            ? new YMap { { "name", environment.Name }, { "resourceType", "VirtualMachine" }, { "tags", environment.ServerLabel } }
            : new YScalar(environment.Name, Raw: false);

        return new YMap
        {
            { "deployment", "Deploy" },
            { "displayName", $"Deploy to {environment.Name}" },
            { "environment", target },
            // A remote deploy to Windows servers needs a Windows agent for WinRM.
            { "pool", spec.DeploysOnMac ? BuildPool(spec) : spec.IsRemote && spec.UsesPowerShell ? new YMap { { "vmImage", "windows-latest" } } : null },
            { "variables", Commands.HasOwnCommands(spec, environment) ? new YMap { { "DEPLOY_ENVIRONMENT", environment.Name } } : null },
            // On servers the environment's machines are updated one at a time; a failure stops before the next one.
            {
                "strategy", spec.OnServerRunner
                    ? new YMap { { "rolling", new YMap { { "maxParallel", "1" }, { "deploy", new YMap { { "steps", steps } } } } } }
                    : new YMap { { "runOnce", new YMap { { "deploy", new YMap { { "steps", steps } } } } } }
            },
        };
    }

    /// <summary>Secret variables are not environment variables in Azure DevOps, so each build step maps the ones it needs.</summary>
    private static YMap? FeedEnv(PipelineSpec spec, bool npmOnly = false) => Env(Feeds.BuildEnv(spec, Platform.AzureDevOps, npmOnly));

    public static string SwaTokenVariable(EnvironmentSpec environment) => "SWA_TOKEN_" + environment.Name.Replace('-', '_').ToUpperInvariant();

    private static YMap SetupTool(PipelineSpec spec)
    {
        var version = spec.Build.EffectiveVersion;
        return spec.Build.Stack switch
        {
            Stack.DotNet => Task("UseDotNet@2", "Install .NET", new YMap { { "packageType", "sdk" }, { "version", version + ".x" } }),
            Stack.Node => Task("NodeTool@0", "Install Node.js", new YMap { { "versionSpec", version + ".x" } }),
            Stack.Python => Task("UsePythonVersion@0", "Install Python", new YMap { { "versionSpec", version } }),
            // The hosted agents have no Elixir or Flutter: they are installed for the run.
            Stack.Elixir => Script("Install Elixir", "sudo apt-get update -qq\nsudo apt-get install -y -qq elixir erlang > /dev/null\nelixir --version"),
            Stack.Flutter => Script("Install Flutter", $"git clone --quiet --depth 1 --branch {version} https://github.com/flutter/flutter.git \"$HOME/flutter\"\necho \"##vso[task.prependpath]$HOME/flutter/bin\""),
            Stack.Go => Task("GoTool@0", "Install Go", new YMap { { "version", version } }),
            Stack.Ruby => Task("UseRubyVersion@0", "Install Ruby", new YMap { { "versionSpec", version } }),
            // The hosted agents have several PHP versions and Composer; this chooses the one asked for.
            Stack.Php => Script("Choose the PHP version", $"sudo update-alternatives --set php /usr/bin/php{version} || echo \"PHP {version} is not on this agent: using the one it has\"\nphp --version"),
            Stack.Rust => Script("Install Rust", $"rustup toolchain install {version} --profile minimal\nrustup default {version}"),
            _ => Task("JavaToolInstaller@0", "Install Java", new YMap
            {
                { "versionSpec", version },
                { "jdkArchitectureOption", "x64" },
                { "jdkSourceOption", "PreInstalled" },
            }),
        };
    }

    private static YMap Task(string task, string name, YMap inputs) => new() { { "task", task }, { "displayName", name }, { "inputs", inputs } };

    private static YMap Download() => new() { { "download", "current" }, { "artifact", "app" } };

    // Every script stops at the first failing command.
    private const string Strict = "set -eo pipefail\n";

    /// <summary>The person's commands: PowerShell on servers, the Azure CLI task when the deploy signs in to Azure, bash otherwise.</summary>
    private static YMap Own(PipelineSpec spec, string connection, string name, string script) =>
        spec.UsesPowerShell ? PowerShell(name, script)
        : spec.NeedsAzure ? AzureCli(name, connection, script)
        : Script(name, script);

    private static YMap Shell(PipelineSpec spec, string name, string script) =>
        spec.UsesPowerShell ? PowerShell(name, script) : Script(name, script);

    private static YMap Publish(string name, string folder, string artifact) => new()
    {
        { "task", "PublishPipelineArtifact@1" },
        { "displayName", name },
        { "inputs", new YMap { { "targetPath", "$(System.DefaultWorkingDirectory)/" + folder }, { "artifact", artifact } } },
    };

    private static YMap? CacheVariables(PipelineSpec spec)
    {
        if (!PackageCache.Applies(spec))
        {
            return null;
        }

        var (key, value) = PackageCache.Variable(spec.Build.Stack, "$(Pipeline.Workspace)");
        return new YMap { { key, value } };
    }

    private static YMap? BuildPool(PipelineSpec spec) => spec.Build.Agent switch
    {
        BuildAgent.HostedWindows => new YMap { { "vmImage", "windows-latest" } },
        BuildAgent.SelfHostedLinux or BuildAgent.SelfHostedWindows or BuildAgent.SelfHostedMac => new YMap { { "name", spec.Build.AgentLabel } },
        BuildAgent.HostedMac => new YMap { { "vmImage", "macOS-latest" } },
        _ => null,
    };

    /// <summary>A build step in the shell of the build agent: bash on Linux, Windows PowerShell on Windows.</summary>
    private static YMap BuildStep(PipelineSpec spec, string name, string script, YMap? env)
    {
        if (!spec.IsWindowsBuild)
        {
            return Script(name, script, env);
        }

        var step = PowerShell(name, script);
        step.Add("env", env);
        return step;
    }

    private static YMap? Env(IReadOnlyList<KeyValuePair<string, string>> values)
    {
        if (values.Count == 0)
        {
            return null;
        }

        var env = new YMap();
        foreach (var (key, value) in values)
        {
            env.Add(key, new YScalar(value, Raw: false));
        }

        return env;
    }

    private static YMap PowerShell(string name, string script) => new()
    {
        { "powershell", script },
        { "displayName", name },
        { "errorActionPreference", "stop" },
    };

    private static YMap Script(string name, string script, YMap? env = null) => new() { { "script", Strict + script }, { "displayName", name }, { "env", env } };

    private static YMap AzureCli(string name, string connection, string script) => Task("AzureCLI@2", name, new YMap
    {
        { "azureSubscription", connection },
        { "scriptType", "bash" },
        { "scriptLocation", "inlineScript" },
        { "inlineScript", Strict + script },
    });
}

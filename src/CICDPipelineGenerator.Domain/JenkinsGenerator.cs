using System.Text;

namespace CICDPipelineGenerator.Domain;

/// <summary>
/// A declarative Jenkinsfile for a multibranch pipeline: a stage for the build and one per environment. Jenkins has
/// no sign-in token of its own, so every variable and secret is a credential (secret text) bound to the stage that
/// uses it: NAME for the build, NAME_ENVIRONMENT for an environment. The agents have the tools the stages run.
/// </summary>
public static class JenkinsGenerator
{
    public const string Path = "Jenkinsfile";
    public const string NotifyCredential = "NOTIFY_WEBHOOK";

    /// <summary>With several applications in the repository, each one has its own file (the job's "Script Path").</summary>
    public static string PathFor(PipelineSpec spec) => spec.SeveralApps ? $"Jenkinsfile-{spec.Name}" : Path;

    public static string RollbackPathFor(PipelineSpec spec) => spec.SeveralApps ? $"Jenkinsfile-{spec.Name}.rollback" : "Jenkinsfile.rollback";

    /// <summary>The credential a stage binds to a variable: the environment's own for a deploy, the shared one for the build.</summary>
    public static string Credential(PlanJob job, string name) =>
        job.Environment is null || name == NotifyCredential ? name : Secrets.AzureDevOpsName(job.Environment, name);

    public static GeneratedFile Generate(PipelineSpec spec)
    {
        var plan = ShellPlan.Create(spec, Platform.Jenkins);
        var text = new StringBuilder();
        text.Append("// Generated by CI/CD Pipeline Generator for ").Append(spec.Name).Append(".\n");
        text.Append("// Before the first run, follow SETUP.md: the multibranch job, credentials, agents and plugins.\n");
        text.Append("pipeline {\n    agent none\n    options {\n        disableConcurrentBuilds()\n    }\n");
        if (!string.IsNullOrWhiteSpace(spec.Schedule))
        {
            text.Append("    triggers {\n        cron('").Append(Quote(spec.Schedule)).Append("')\n    }\n");
        }

        text.Append("    stages {\n");
        foreach (var job in plan.Jobs)
        {
            Stage(text, spec, job, When(spec, job));
        }

        text.Append("    }\n}\n");
        return new(PathFor(spec), text.ToString());
    }

    /// <summary>A pipeline started by hand (Build with Parameters) that puts the previous version of one environment back.</summary>
    public static GeneratedFile Rollback(PipelineSpec spec)
    {
        var plan = ShellPlan.Create(spec, Platform.Jenkins);
        var text = new StringBuilder();
        text.Append("// Generated by CI/CD Pipeline Generator for ").Append(spec.Name).Append(".\n");
        text.Append("// Run it by hand (Build with Parameters) to put the previous version back.\n");
        text.Append("pipeline {\n    agent none\n    parameters {\n        choice(name: 'ENVIRONMENT', choices: [")
            .Append(string.Join(", ", spec.Environments.Select(environment => $"'{Quote(environment.Name)}'")))
            .Append("], description: 'The environment that goes back to its previous version')\n    }\n    stages {\n");
        foreach (var job in plan.Rollbacks)
        {
            Stage(text, spec, job, [$"expression {{ params.ENVIRONMENT == '{Quote(job.Environment!.Name)}' }}"]);
        }

        text.Append("    }\n}\n");
        return new(RollbackPathFor(spec), text.ToString());
    }

    /// <summary>The conditions a stage runs under: the branch or tag that deploys, never a pull request, and the paths asked for.</summary>
    private static List<string> When(PipelineSpec spec, PlanJob job)
    {
        var conditions = new List<string>();
        if (job.NotOnPullRequests)
        {
            if (spec.Flow == Flow.Tag)
            {
                conditions.Add($"tag '{Quote(spec.TagPattern)}'");
            }
            else
            {
                var branches = job.Environment is null ? spec.DeployBranches() : [spec.BranchOf(job.Environment)];
                conditions.Add(branches.Count == 1 ? $"branch '{Quote(branches[0])}'" : "anyOf { " + string.Join("; ", branches.Select(branch => $"branch '{Quote(branch)}'")) + " }");
            }
        }
        else if (!spec.BuildPullRequests)
        {
            conditions.Add("not { changeRequest() }");
        }

        if (spec.PathFilters.Count > 0 && spec.Flow != Flow.Tag)
        {
            // A run started by hand or by the schedule has no changes to look at, so it always runs.
            conditions.Add("anyOf { " + string.Join("; ", spec.PathFilters.Select(path => $"changeset '{Quote(path)}'")) + "; triggeredBy cause: 'UserIdCause'; triggeredBy 'TimerTrigger' }");
        }

        return conditions;
    }

    private static void Stage(StringBuilder text, PipelineSpec spec, PlanJob job, List<string> conditions)
    {
        const string Pad = "            ";
        text.Append("        stage('").Append(Quote(job.Name)).Append("') {\n");
        if (conditions.Count > 0)
        {
            // Decided before an agent is taken and before anyone is asked to approve.
            text.Append(Pad).Append("when {\n").Append(Pad).Append("    beforeAgent true\n").Append(Pad).Append("    beforeInput true\n");
            foreach (var condition in conditions)
            {
                text.Append(Pad).Append("    ").Append(condition).Append('\n');
            }

            text.Append(Pad).Append("}\n");
        }

        text.Append(Pad).Append(job.Label is not null ? $"agent {{ label '{Quote(job.Label)}' }}" : job.Windows ? "agent { label 'windows' }" : job.Mac ? "agent { label 'macos' }" : "agent any").Append('\n');
        if (job.Environment is { RequireApproval: true } && !job.IsRollback)
        {
            text.Append(Pad).Append("input {\n").Append(Pad).Append("    message 'Deploy to ").Append(Quote(job.Environment.Name)).Append("?'\n").Append(Pad).Append("}\n");
        }

        var options = new List<string>();
        if (job.Environment is not null)
        {
            // One deployment at a time per environment (Lockable Resources plugin).
            options.Add($"lock('{Quote(spec.Name)}-{Quote(job.Environment.Name)}')");
        }

        if (!job.Checkout)
        {
            options.Add("skipDefaultCheckout()");
        }

        if (options.Count > 0)
        {
            text.Append(Pad).Append("options {\n");
            foreach (var option in options)
            {
                text.Append(Pad).Append("    ").Append(option).Append('\n');
            }

            text.Append(Pad).Append("}\n");
        }

        var notify = (spec.NotifyOnFailure || job.NotifiesSuccess) && !job.Windows;
        var variables = notify ? job.Variables.Append(NotifyCredential).Distinct().ToList() : job.Variables;
        if (variables.Count > 0)
        {
            text.Append(Pad).Append("environment {\n");
            foreach (var variable in variables)
            {
                text.Append(Pad).Append("    ").Append(variable).Append(" = credentials('").Append(Quote(Credential(job, variable))).Append("')\n");
            }

            text.Append(Pad).Append("}\n");
        }

        text.Append(Pad).Append("steps {\n");
        if (job.UsesBuild)
        {
            text.Append(Pad).Append("    unstash 'build'\n");
        }

        foreach (var step in job.Steps)
        {
            // Each step is its own shell, so the sign-in comes with every one that follows it.
            var script = job.Windows
                ? (step.Script.StartsWith("$ErrorActionPreference", StringComparison.Ordinal) ? "" : "$ErrorActionPreference = 'Stop'\n") + Systems.WithEnv(step.Script, step.Env, powerShell: true)
                : "#!/bin/bash\nset -eo pipefail\n" + (job.Preamble.Length > 0 ? job.Preamble + "\n" : "") + Systems.WithEnv(step.Script, step.Env, powerShell: false);
            text.Append(Pad).Append("    ").Append(job.Windows ? "powershell" : "sh").Append(" label: '").Append(Quote(step.Name)).Append("', script: '''").Append(Quote(script.TrimEnd('\n'))).Append("\n'''\n");
        }

        if (job.Keeps.Count > 0)
        {
            text.Append(Pad).Append("    stash name: 'build', includes: '").Append(string.Join(",", job.Keeps.Select(folder => folder + "/**"))).Append("'\n");
        }

        text.Append(Pad).Append("}\n");
        if (job.Results.Count > 0 || job.JUnit is not null || notify)
        {
            text.Append(Pad).Append("post {\n");
            if (job.Results.Count > 0 || job.JUnit is not null)
            {
                text.Append(Pad).Append("    always {\n");
                if (job.JUnit is not null)
                {
                    text.Append(Pad).Append("        junit testResults: '").Append(job.JUnit).Append("', allowEmptyResults: true\n");
                }

                foreach (var results in job.Results)
                {
                    text.Append(Pad).Append("        archiveArtifacts artifacts: '").Append(results).Append("/**', allowEmptyArchive: true\n");
                }

                text.Append(Pad).Append("    }\n");
            }

            if (job.NotifiesSuccess)
            {
                var done = $"export WEBHOOK=\"$NOTIFY_WEBHOOK\" TEXT=\"{spec.Name} is deployed to {job.Environment!.Name}: {Systems.RunUrl(Platform.Jenkins)}\"\n{Commands.Notify}";
                text.Append(Pad).Append("    success {\n").Append(Pad).Append("        sh label: 'Tell the team it is deployed', script: \'\'\'").Append(Quote(done)).Append("\n\'\'\'\n").Append(Pad).Append("    }\n");
            }

            if (notify && spec.NotifyOnFailure)
            {
                var script = $"export WEBHOOK=\"$NOTIFY_WEBHOOK\" TEXT=\"The pipeline of {spec.Name} failed: {Systems.RunUrl(Platform.Jenkins)}\"\n{Commands.Notify}";
                text.Append(Pad).Append("    failure {\n").Append(Pad).Append("        sh label: 'Tell the team it failed', script: '''").Append(Quote(script)).Append("\n'''\n").Append(Pad).Append("    }\n");
            }

            text.Append(Pad).Append("}\n");
        }

        text.Append("        }\n");
    }

    /// <summary>Text inside a Groovy single-quoted string, where nothing is replaced: only the backslash and the quote are special.</summary>
    public static string Quote(string text) => text.Replace("\\", "\\\\", StringComparison.Ordinal).Replace("'", "\\'", StringComparison.Ordinal);
}

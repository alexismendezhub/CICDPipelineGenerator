    /// <summary>
    /// Azure DevOps: a service connection per environment with workload identity federation over the environment's
    /// identity, the environments, the pipeline (for a repository of Azure Repos) and its secret variables.
    /// </summary>
    public static GeneratedFile AzureDevOps(PipelineSpec spec, bool powerShell = false)
    {
        var script = new Script(powerShell);
        script.Start(spec, "Azure DevOps", "Azure", "`az login` (as someone who may create identities and assign roles), with the extension `az extension add --name azure-devops`");
        script.Argument(1, "ORG", null, "The organization, as https://dev.azure.com/my-organization");
        script.Argument(2, "PROJECT", null, "The project name");
        script.Argument(3, "REPOSITORY", spec.Name, comment: $"the repository in Azure Repos that has {AzureDevOpsGenerator.PathFor(spec)}");
        LocationArguments(script, spec, 4);
        script.Run("az devops configure --defaults organization=\"$ORG\" project=\"$PROJECT\"");
        script.Set("tenant", "az account show --query tenantId --output tsv");
        script.Set("subscription", "az account show --query id --output tsv");
        script.Set("subscription_name", "az account show --query name --output tsv");
        script.Set("project_id", "az devops project show --project \"$PROJECT\" --query id --output tsv");
        script.Line();
        var first = true;
        foreach (var environment in spec.Environments)
        {
            var identity = Identity(spec, environment);
            var group = environment.ResourceGroup;
            var connection = environment.ServiceConnection;
            script.Comment($"---- {environment.Name}");
            if (string.IsNullOrWhiteSpace(group) || string.IsNullOrWhiteSpace(connection))
            {
                script.Echo($"{environment.Name} has no resource group or service connection in the settings: create its connection by hand, as SETUP.md says.");
                script.Line();
                continue;
            }

            EnsureResources(script, spec, environment);
            CreateIdentity(script, spec, environment);
            script.Set("endpoint", $"az devops service-endpoint list --query \"[?name=='{connection}'].id | [0]\" --output tsv");
            script.IfEmpty("endpoint", () =>
            {
                script.File("setup-connection.json",
                [
                    "{",
                    "  \"data\": { \"subscriptionId\": \"$subscription\", \"subscriptionName\": \"$subscription_name\", \"environment\": \"AzureCloud\", \"scopeLevel\": \"Subscription\", \"creationMode\": \"Manual\" },",
                    $"  \"name\": \"{connection}\", \"type\": \"AzureRM\", \"url\": \"https://management.azure.com/\",",
                    "  \"authorization\": { \"parameters\": { \"tenantid\": \"$tenant\", \"serviceprincipalid\": \"$client\" }, \"scheme\": \"WorkloadIdentityFederation\" },",
                    "  \"isShared\": false, \"isReady\": true,",
                    $"  \"serviceEndpointProjectReferences\": [ {{ \"projectReference\": {{ \"id\": \"$project_id\", \"name\": \"$PROJECT\" }}, \"name\": \"{connection}\" }} ]",
                    "}",
                ]);
                script.Set("endpoint", "az devops service-endpoint create --service-endpoint-configuration setup-connection.json --query id --output tsv");
            });

            // Azure DevOps says which issuer and subject its tokens for this connection carry; the identity trusts exactly those.
            script.Set("issuer", "az devops service-endpoint show --id \"$endpoint\" --query authorization.parameters.workloadIdentityFederationIssuer --output tsv");
            script.Set("subject", "az devops service-endpoint show --id \"$endpoint\" --query authorization.parameters.workloadIdentityFederationSubject --output tsv");
            script.Run($"az identity federated-credential create --name azure-devops-{environment.Name} --identity-name {identity} --resource-group {group} --issuer \"$issuer\" --subject \"$subject\" --audiences api://AzureADTokenExchange --output none");
            GrantRoles(script, spec, environment, first);
            script.Set("found", $"az devops invoke --area distributedtask --resource environments --route-parameters project=\"$PROJECT\" --api-version 7.1 --query \"value[?name=='{environment.Name}'].name | [0]\" --output tsv");
            script.IfEmpty("found", () =>
            {
                script.File("setup-environment.json", [$"{{ \"name\": \"{environment.Name}\" }}"]);
                script.Run("az devops invoke --area distributedtask --resource environments --route-parameters project=\"$PROJECT\" --http-method POST --in-file setup-environment.json --api-version 7.1 --output none");
            });
            if (environment.RequireApproval)
            {
                script.Echo($"{environment.Name} needs approval: add who approves in Pipelines, Environments, {environment.Name}, Approvals and checks.");
            }

            script.Line();
            first = false;
        }

        var secrets = spec.Environments.SelectMany(environment => Secrets.Names(spec, environment).Select(name => Secrets.AzureDevOpsName(environment, name))).Distinct().ToList();
        script.Comment("---- the pipeline");
        script.Unless(
            $"az pipelines show --name {spec.Name}",
            $"az pipelines create --name {spec.Name} --repository \"$REPOSITORY\" --repository-type tfsgit --branch {spec.MainBranch} --yml-path {AzureDevOpsGenerator.PathFor(spec)} --skip-first-run true --output none");
        foreach (var secret in secrets)
        {
            script.SetIfAny("there", $"az pipelines variable list --pipeline-name {spec.Name} --query {secret}.isSecret --output tsv");
            script.IfEmpty("there", () =>
            {
                script.Ask("value", $"The value of the secret {secret}");
                script.Run($"az pipelines variable create --pipeline-name {spec.Name} --name {secret} --secret true --value \"$value\" --output none");
            });
        }

        // This pipeline alone may use each connection and environment, so its first run does not stop to ask.
        script.Set("pipeline", $"az pipelines show --name {spec.Name} --query id --output tsv");
        script.File("setup-permission.json", ["{ \"pipelines\": [ { \"id\": $pipeline, \"authorized\": true } ] }"]);
        foreach (var environment in spec.Environments.Where(environment => !string.IsNullOrWhiteSpace(environment.ResourceGroup) && !string.IsNullOrWhiteSpace(environment.ServiceConnection)))
        {
            script.Set("endpoint", $"az devops service-endpoint list --query \"[?name=='{environment.ServiceConnection}'].id | [0]\" --output tsv");
            script.Set("found", $"az devops invoke --area distributedtask --resource environments --route-parameters project=\"$PROJECT\" --api-version 7.1 --query \"value[?name=='{environment.Name}'].id | [0]\" --output tsv");
            script.Run("az devops invoke --area pipelinePermissions --resource pipelinePermissions --route-parameters project=\"$PROJECT\" resourceType=endpoint resourceId=\"$endpoint\" --http-method PATCH --in-file setup-permission.json --api-version 7.1-preview --output none");
            script.Run("az devops invoke --area pipelinePermissions --resource pipelinePermissions --route-parameters project=\"$PROJECT\" resourceType=environment resourceId=\"$found\" --http-method PATCH --in-file setup-permission.json --api-version 7.1-preview --output none");
        }

        script.Remove("setup-connection.json setup-environment.json setup-permission.json");
        script.Echo("Done. Run the pipeline: it may already use its service connections and environments.");
        return script.ToFile(AzureDevOpsPath);
    }

    /// <summary>GitLab: each environment's identity trusts the project's branch that deploys to it, and the project gets the variables.</summary>
    public static GeneratedFile GitLab(PipelineSpec spec, bool powerShell = false)
    {
        var script = new Script(powerShell);
        script.Start(spec, "GitLab", "Azure", "`az login` (as someone who may create identities and assign roles) and `glab auth login`");
        script.Argument(1, "REPO", spec.Repository);
        script.Argument(2, "GITLAB_URL", "https://gitlab.com", comment: "your own address on a self-managed GitLab");
        LocationArguments(script, spec, 3);
        script.Set("tenant", "az account show --query tenantId --output tsv");
        script.Set("subscription", "az account show --query id --output tsv");
        script.Echo("Project $REPO, subscription $subscription");
        script.Line();

        // A variable of the project: created, or given its new value when it is already there.
        void Variable(string name, string value, string options = "") => script.Either(
            $"glab variable set {name} --value \"{value}\" --repo \"$REPO\"{options}",
            $"glab variable update {name} --value \"{value}\" --repo \"$REPO\"{options}");

        Variable("AZURE_TENANT_ID", "$tenant");
        Variable("AZURE_SUBSCRIPTION_ID", "$subscription");
        var first = true;
        foreach (var environment in spec.Environments)
        {
            var identity = Identity(spec, environment);
            var group = environment.ResourceGroup;
            script.Line();
            script.Comment($"---- {environment.Name}");
            if (string.IsNullOrWhiteSpace(group))
            {
                script.Echo($"{environment.Name} has no resource group in the settings: create its identity by hand, as SETUP.md says.");
                continue;
            }

            EnsureResources(script, spec, environment);
            CreateIdentity(script, spec, environment);
            script.Run($"az identity federated-credential create --name gitlab-{environment.Name} --identity-name {identity} --resource-group {group} --issuer \"$GITLAB_URL\" --subject \"project_path:${{REPO}}:ref_type:branch:ref:{spec.BranchOf(environment)}\" --audiences api://AzureADTokenExchange --output none");
            Variable("AZURE_CLIENT_ID", "$client", $" --scope {environment.Name}");
            if (first)
            {
                // Jobs without an environment (the build) use the value without a scope.
                Variable("AZURE_CLIENT_ID", "$client");
            }

            GrantRoles(script, spec, environment, first);
            foreach (var secret in Secrets.Names(spec, environment))
            {
                script.Ask("value", $"The value of the secret {secret} of {environment.Name}");
                Variable(secret, "$value", $" --scope {environment.Name} --masked");
            }

            if (environment.RequireApproval)
            {
                script.Echo($"{environment.Name} waits for someone to start its job; to limit who may, protect the environment in Settings, CI/CD, Protected environments.");
            }

            first = false;
        }

        script.Line();
        script.Echo("Done. Commit the pipeline file and push.");
        return script.ToFile(GitLabPath);
    }

    private static string Slug(string branch) => new([.. branch.Select(character => char.IsAsciiLetterOrDigit(character) ? character : '-')]);

    /// <summary>The narrowest built-in role each target needs, on the resource the environment names.</summary>
    private static IEnumerable<(string Role, string Scope)> Roles(PipelineSpec spec, EnvironmentSpec environment, bool builds)
    {
        var deploy = spec.Deploy;
        var group = $"/subscriptions/$subscription/resourceGroups/{environment.ResourceGroup}";
        switch (deploy.Target)
        {
            case Target.AppService or Target.FunctionApp:
                yield return ("Website Contributor", $"{group}/providers/Microsoft.Web/sites/{environment.ResourceName}");
                break;
            case Target.ContainerApp:
                yield return ("Contributor", $"{group}/providers/Microsoft.App/containerApps/{environment.ResourceName}");
                yield return ("Contributor", "$managed");
                break;
            case Target.Aks:
                yield return ("Azure Kubernetes Service Cluster User Role", $"{group}/providers/Microsoft.ContainerService/managedClusters/{environment.ResourceName}");
                yield return ("Azure Kubernetes Service RBAC Writer", $"{group}/providers/Microsoft.ContainerService/managedClusters/{environment.ResourceName}/namespaces/{deploy.Namespace}");
                break;
            case Target.Terraform:
                yield return ("Contributor", group);
                yield return ("Storage Blob Data Contributor", "$state");
                break;
            default:
                // Templates and your own commands change what is in the environment's resource group.
                yield return ("Contributor", group);
                break;
        }

        if (builds)
        {
            yield return ("Contributor", "$registry");
        }
    }

using System.Text;

namespace CICDPipelineGenerator.Domain;

/// <summary>
/// The one-time setup as scripts, in bash and in PowerShell: the identities or roles of each environment, what they
/// trust and may do, the environments of the pipeline system and their variables. They do what SETUP.md describes,
/// so the pipeline runs after one command; secrets are asked for, never written.
/// </summary>
public static class SetupScript
{
    public const string Path = "setup/setup-github.sh";
    public const string AzureDevOpsPath = "setup/setup-azure-devops.sh";
    public const string GitLabPath = "setup/setup-gitlab.sh";

    /// <summary>The same script for PowerShell.</summary>
    public static string PowerShellPath(string path) => path[..^3] + ".ps1";

    private static bool Wanted(PipelineSpec spec) => spec.SetupScript && !spec.SeveralApps;

    private static bool Azure(PipelineSpec spec) => Wanted(spec) && spec.NeedsAzure && spec.Deploy.Target != Target.StaticWebApp;

    private static bool Cloud(PipelineSpec spec) => Wanted(spec) && (spec.IsAws || (spec.IsGcp && spec.Deploy.Target != Target.FirebaseHosting)) && !spec.IsInfrastructure;

    public static bool Applies(PipelineSpec spec) => (Azure(spec) || Cloud(spec)) && spec.Platforms.Contains(Platform.GitHubActions) && !string.IsNullOrWhiteSpace(spec.Repository);

    public static bool AppliesToAzureDevOps(PipelineSpec spec) => Azure(spec) && spec.Platforms.Contains(Platform.AzureDevOps);

    // A tag deploys from a ref that changes with every tag, which a federated credential cannot name: SETUP.md says how.
    public static bool AppliesToGitLab(PipelineSpec spec) =>
        Azure(spec) && spec.Platforms.Contains(Platform.GitLab) && !string.IsNullOrWhiteSpace(spec.Repository) && spec.Flow != Flow.Tag;

    public static IEnumerable<GeneratedFile> All(PipelineSpec spec)
    {
        foreach (var powerShell in new[] { false, true })
        {
            if (Applies(spec))
            {
                yield return Generate(spec, powerShell);
            }

            if (AppliesToAzureDevOps(spec))
            {
                yield return AzureDevOps(spec, powerShell);
            }

            if (AppliesToGitLab(spec))
            {
                yield return GitLab(spec, powerShell);
            }
        }
    }

    /// <summary>
    /// Writes each step once for both shells. A variable is read as $name or ${name} in either; what differs (setting
    /// one, stopping at an error, asking for a secret, writing a file) is written the way each shell does it.
    /// </summary>
    private sealed class Script(bool powerShell)
    {
        private readonly StringBuilder text = new();
        private string indent = "";

        public bool PowerShell => powerShell;

        public void Line(string line = "") => text.Append(line.Length == 0 ? "" : indent + line).Append('\n');

        public void Comment(string comment) => Line("# " + comment);

        /// <summary>PowerShell does not stop when a program fails, so every command that must work is checked.</summary>
        private string Checked => powerShell ? "; if ($LASTEXITCODE -ne 0) { throw 'The setup stopped: the command above failed.' }" : "";

        public void Start(PipelineSpec spec, string system, string cloud, string signedIn)
        {
            if (!powerShell)
            {
                Line("#!/usr/bin/env bash");
            }

            Comment($"Generated by CI/CD Pipeline Generator for {spec.Name}.");
            Comment($"The one-time setup of {system} and {cloud}. Run it once from {(powerShell ? "PowerShell" : "bash (Git Bash, WSL or Cloud Shell)")},");
            Comment($"signed in with {signedIn}.");
            Comment("It can be run again: what already exists is kept.");
            if (powerShell)
            {
                // Every command is checked by its exit code; with 'Stop', Windows PowerShell would also stop at the text a
                // program writes to its error output, even when the script expects that program to fail.
                Line("$ErrorActionPreference = 'Continue'");
            }
            else
            {
                Line("set -euo pipefail");
                Line();
                Comment("Git Bash on Windows would rewrite a value that starts with / into a Windows path.");
                Line("export MSYS_NO_PATHCONV=1");
            }

            Line();
        }

        /// <summary>An argument of the script: the first, second or third word after its name.</summary>
        public void Argument(int position, string name, string? fallback, string? needed = null, string? comment = null)
        {
            var note = comment is null ? "" : " # " + comment;
            if (powerShell)
            {
                Line(fallback is null
                    ? $"if ($args.Count -lt {position}) {{ throw '{needed}' }}; ${name} = $args[{position - 1}]{note}"
                    : $"${name} = if ($args.Count -ge {position}) {{ $args[{position - 1}] }} else {{ '{fallback}' }}{note}");
            }
            else
            {
                Line(fallback is null ? $"{name}=\"${{{position}:?{needed}}}\"{note}" : $"{name}=\"${{{position}:-{fallback}}}\"{note}");
            }
        }

        /// <summary>A variable with what a command prints.</summary>
        public void Set(string name, string command) => Line(powerShell ? $"${name} = {command}{Checked}" : $"{name}=$({command})");

        /// <summary>A variable with what a command prints, or nothing when the command fails.</summary>
        public void SetIfAny(string name, string command) => Line(powerShell ? $"${name} = {command} 2>$null" : $"{name}=$({command} 2> /dev/null || true)");

        public void Assign(string name, string value) => Line(powerShell ? $"${name} = \"{value}\"" : $"{name}=\"{value}\"");

        public void Default(string name, string value) => Line(powerShell ? $"if (-not ${name}) {{ ${name} = \"{value}\" }}" : $"{name}=\"${{{name}:-{value}}}\"");

        public void Run(string command, bool quiet = false) => Line(command + (quiet ? powerShell ? " | Out-Null" : " > /dev/null" : "") + Checked);

        /// <summary>Runs the command only when the test fails (the thing is not there yet).</summary>
        public void Unless(string test, string command) => Line(powerShell
            ? $"{test} *> $null; if ($LASTEXITCODE -ne 0) {{ {command}{Checked} }}"
            : $"{test} > /dev/null 2>&1 || {command}");

        /// <summary>The first command, or the second when the first fails.</summary>
        public void Either(string first, string second) => Line(powerShell
            ? $"{first} 2>$null; if ($LASTEXITCODE -ne 0) {{ {second}{Checked} }}"
            : $"{first} 2> /dev/null || {second}");

        public void Echo(string message) => Line(powerShell ? $"Write-Host \"{message}\"" : $"echo \"{message}\"");

        /// <summary>Asks for a secret without showing it.</summary>
        public void Ask(string name, string prompt) => Line(powerShell
            ? $"${name} = [Runtime.InteropServices.Marshal]::PtrToStringBSTR([Runtime.InteropServices.Marshal]::SecureStringToBSTR((Read-Host \"{prompt}\" -AsSecureString)))"
            : $"read -r -s -p \"{prompt}: \" {name}; echo");

        /// <summary>A file in the current folder, with the variables in its lines filled in.</summary>
        public void File(string name, IEnumerable<string> lines)
        {
            Line(powerShell ? "@\"" : $"cat > {name} <<JSON");
            foreach (var line in lines)
            {
                text.Append(line).Append('\n');
            }

            if (powerShell)
            {
                text.Append("\"@ | Set-Content ").Append(name).Append(" -Encoding ascii\n");
            }
            else
            {
                text.Append("JSON\n");
            }
        }

        public void Remove(string names) => Line(powerShell ? $"Remove-Item {names.Replace(" ", ", ", StringComparison.Ordinal)} -ErrorAction SilentlyContinue" : $"rm -f {names}");

        public void Sleep(int seconds, string why) => Line((powerShell ? $"Start-Sleep -Seconds {seconds}" : $"sleep {seconds}") + " # " + why);

        public void IfEmpty(string name, Action body) => Block(powerShell ? $"if (-not ${name}) {{" : $"if [ -z \"${name}\" ]; then", body);

        private void Block(string open, Action body)
        {
            Line(open);
            indent += "  ";
            body();
            indent = indent[..^2];
            Line(powerShell ? "}" : "fi");
        }

        public GeneratedFile ToFile(string path) => new(powerShell ? PowerShellPath(path) : path, text.ToString());
    }

    private static string Identity(PipelineSpec spec, EnvironmentSpec environment) => $"id-{spec.Name}-{environment.Name}-deploy";

    /// <summary>The identity of an environment, with $client and $principal set for what follows.</summary>
    private static void CreateIdentity(Script script, PipelineSpec spec, EnvironmentSpec environment)
    {
        var identity = Identity(spec, environment);
        var group = environment.ResourceGroup;
        script.Run($"az identity create --name {identity} --resource-group {group} --output none");
        script.Set("client", $"az identity show --name {identity} --resource-group {group} --query clientId --output tsv");
        script.Set("principal", $"az identity show --name {identity} --resource-group {group} --query principalId --output tsv");
    }

    /// <summary>The App Service runtime of the build's language, as `az webapp create --runtime` names it.</summary>
    private static string? Runtime(PipelineSpec spec)
    {
        var version = spec.Build.EffectiveVersion;
        var linux = spec.Deploy.Os == HostOs.Linux;
        return spec.Build.Stack switch
        {
            Stack.DotNet => linux ? $"DOTNETCORE:{version}" : $"dotnet:{version.Split('.')[0]}",
            Stack.Node => linux ? $"NODE:{version}-lts" : $"NODE:{version}LTS",
            Stack.Python when linux => $"PYTHON:{version}",
            Stack.Java or Stack.Gradle when linux => $"JAVA:{version}-java{version}",
            Stack.Php when linux => $"PHP:{version}",
            _ => null,
        };
    }

    /// <summary>
    /// What the environment deploys to, when it is not there yet: its resource group and, for App Service, the plan
    /// and the web app. The free plan is enough to deploy; slots (blue-green, canary, previews) need Standard.
    /// </summary>
    private static void EnsureResources(Script script, PipelineSpec spec, EnvironmentSpec environment)
    {
        var group = environment.ResourceGroup;
        script.Unless($"az group show --name {group}", $"az group create --name {group} --location \"$LOCATION\" --output none");
        if (spec.Deploy.Target != Target.AppService || Runtime(spec) is not { } runtime || string.IsNullOrWhiteSpace(environment.ResourceName))
        {
            return;
        }

        var app = environment.ResourceName;
        var plan = $"plan-{spec.Name}-{environment.Name}";
        script.SetIfAny("site", $"az webapp show --name {app} --resource-group {group} --query name --output tsv");
        script.IfEmpty("site", () =>
        {
            script.Run($"az appservice plan create --name {plan} --resource-group {group} --location \"$LOCATION\" --sku \"$SKU\"{(spec.Deploy.Os == HostOs.Linux ? " --is-linux" : "")} --output none");
            script.Run($"az webapp create --name {app} --resource-group {group} --plan {plan} --runtime \"{runtime}\" --output none");
        });
        if (!string.IsNullOrWhiteSpace(environment.Slot))
        {
            script.Unless($"az webapp deployment slot show --name {app} --resource-group {group} --slot {environment.Slot}", $"az webapp deployment slot create --name {app} --resource-group {group} --slot {environment.Slot} --output none");
        }
    }

    private static void LocationArguments(Script script, PipelineSpec spec, int position)
    {
        // Slots (blue-green, canary, a preview per pull request) need the Standard plan or higher.
        var slots = spec.Deploy.Target == Target.AppService && (spec.Deploy.PreviewPullRequests || spec.Environments.Any(environment => !string.IsNullOrWhiteSpace(environment.Slot)));
        script.Argument(position, "LOCATION", "eastus", comment: "where a resource group or web app that is missing is created; choose another when the subscription has no quota there");
        script.Argument(position + 1, "SKU", slots ? "S1" : "F1", comment: slots ? "the plan of a web app that is created: slots need S1 or higher, which is paid" : "the plan of a web app that is created: F1 is free");
    }

    private static void GrantRoles(Script script, PipelineSpec spec, EnvironmentSpec environment, bool first)
    {
        var deploy = spec.Deploy;
        var builds = first && spec.IsAzureContainer;
        if (builds)
        {
            script.Set("registry", $"az acr show --name {deploy.Registry} --query id --output tsv");
        }

        if (deploy.Target == Target.ContainerApp)
        {
            // A change of the app joins it to its environment again, which the environment must allow.
            script.Set("managed", $"az containerapp show --name {environment.ResourceName} --resource-group {environment.ResourceGroup} --query properties.managedEnvironmentId --output tsv");
        }

        if (deploy.Target == Target.Terraform)
        {
            script.Set("state", $"az storage account show --name {deploy.StateStorageAccount} --query id --output tsv");
        }

        script.Sleep(15, "a new identity takes a moment to be known to the role assignments");
        foreach (var (role, scope) in Roles(spec, environment, builds))
        {
            // The role, on the resource alone; a role that is already assigned is left as it is.
            script.Run($"az role assignment create --assignee-object-id \"$principal\" --assignee-principal-type ServicePrincipal --role \"{role}\" --scope \"{scope}\" --output none");
        }
    }

    /// <summary>The start of the subject of the repository's tokens, as GitHub itself says it.</summary>
    private static void GitHubPrefix(Script script)
    {
        script.Comment("The start of the subject of the repository's tokens: repo:owner@id/name@id on repositories created, renamed or");
        script.Comment("transferred since July 2026, repo:owner/name on older ones. GitHub says which.");
        script.SetIfAny("prefix", "gh api \"repos/$REPO/actions/oidc/customization/sub\" --jq '.sub_claim_prefix // empty'");
        script.Default("prefix", "repo:$REPO");
    }

    private static void GitHubSecrets(Script script, PipelineSpec spec, EnvironmentSpec environment)
    {
        foreach (var secret in Secrets.Names(spec, environment))
        {
            script.Echo($"The value of the secret {secret} of {environment.Name}:");
            script.Run($"gh secret set {secret} --repo \"$REPO\" --env {environment.Name}");
        }

        if (environment.RequireApproval)
        {
            script.Echo($"{environment.Name} needs approval: choose who approves in Settings, Environments, {environment.Name}, Required reviewers.");
        }
    }

    public static GeneratedFile Generate(PipelineSpec spec, bool powerShell = false) =>
        spec.IsAws ? GitHubAws(spec, powerShell) : spec.IsGcp ? GitHubGoogle(spec, powerShell) : GitHubAzure(spec, powerShell);

    private static GeneratedFile GitHubAzure(PipelineSpec spec, bool powerShell)
    {
        var script = new Script(powerShell);
        script.Start(spec, "GitHub Actions", "Azure", "`az login` (as someone who may create identities and assign roles) and `gh auth login`");
        script.Argument(1, "REPO", spec.Repository);
        LocationArguments(script, spec, 2);
        script.Set("tenant", "az account show --query tenantId --output tsv");
        script.Set("subscription", "az account show --query id --output tsv");
        GitHubPrefix(script);
        script.Echo("Repository $REPO ($prefix), subscription $subscription");
        script.Line();
        script.Run("gh variable set AZURE_TENANT_ID --repo \"$REPO\" --body \"$tenant\"");
        script.Run("gh variable set AZURE_SUBSCRIPTION_ID --repo \"$REPO\" --body \"$subscription\"");
        var first = true;
        foreach (var environment in spec.Environments)
        {
            var identity = Identity(spec, environment);
            var group = environment.ResourceGroup;
            script.Line();
            script.Comment($"---- {environment.Name}");
            if (string.IsNullOrWhiteSpace(group))
            {
                script.Echo($"{environment.Name} has no resource group in the settings: create its identity by hand, as SETUP.md says.");
                continue;
            }

            script.Run($"gh api --method PUT \"repos/$REPO/environments/{environment.Name}\"", quiet: true);
            EnsureResources(script, spec, environment);
            CreateIdentity(script, spec, environment);
            script.Run($"az identity federated-credential create --name github-{environment.Name} --identity-name {identity} --resource-group {group} --issuer https://token.actions.githubusercontent.com --subject \"${{prefix}}:environment:{environment.Name}\" --audiences api://AzureADTokenExchange --output none");
            script.Run($"gh variable set AZURE_CLIENT_ID --repo \"$REPO\" --env {environment.Name} --body \"$client\"");
            if (first)
            {
                // Jobs without an environment (the build) sign in with the repository's value.
                script.Run("gh variable set AZURE_CLIENT_ID --repo \"$REPO\" --body \"$client\"");
                if (spec.IsAzureContainer)
                {
                    foreach (var branch in spec.DeployBranches())
                    {
                        script.Run($"az identity federated-credential create --name github-branch-{Slug(branch)} --identity-name {identity} --resource-group {group} --issuer https://token.actions.githubusercontent.com --subject \"${{prefix}}:ref:refs/heads/{branch}\" --audiences api://AzureADTokenExchange --output none");
                    }
                }
            }

            GrantRoles(script, spec, environment, first);
            GitHubSecrets(script, spec, environment);
            first = false;
        }

        script.Line();
        script.Echo("Done. Commit the workflow and push.");
        return script.ToFile(Path);
    }

    /// <summary>AWS: GitHub as an identity provider of the account, and a role per environment that only that environment's jobs may take.</summary>
    private static GeneratedFile GitHubAws(PipelineSpec spec, bool powerShell)
    {
        var script = new Script(powerShell);
        script.Start(spec, "GitHub Actions", "AWS", "the AWS CLI (as someone who may create IAM roles) and `gh auth login`");
        script.Argument(1, "REPO", spec.Repository);
        script.Set("account", "aws sts get-caller-identity --query Account --output text");
        script.Assign("provider", "arn:aws:iam::${account}:oidc-provider/token.actions.githubusercontent.com");
        GitHubPrefix(script);
        script.Echo("Repository $REPO ($prefix), account $account");
        script.Line();
        script.Unless("aws iam get-open-id-connect-provider --open-id-connect-provider-arn \"$provider\"", "aws iam create-open-id-connect-provider --url https://token.actions.githubusercontent.com --client-id-list sts.amazonaws.com --output text");
        var policies = AwsPolicies(spec);

        void Role(string role, IEnumerable<string> subjects, string variable)
        {
            // Only tokens of this repository with exactly this subject may take the role.
            script.File("setup-trust.json",
            [
                "{ \"Version\": \"2012-10-17\", \"Statement\": [ { \"Effect\": \"Allow\", \"Principal\": { \"Federated\": \"$provider\" }, \"Action\": \"sts:AssumeRoleWithWebIdentity\",",
                "  \"Condition\": { \"StringEquals\": { \"token.actions.githubusercontent.com:aud\": \"sts.amazonaws.com\",",
                $"    \"token.actions.githubusercontent.com:sub\": [ {string.Join(", ", subjects.Select(subject => $"\"{subject}\""))} ] }} }} }} ] }}",
            ]);
            script.Unless($"aws iam get-role --role-name {role}", $"aws iam create-role --role-name {role} --assume-role-policy-document file://setup-trust.json --output text");
            script.Run($"aws iam update-assume-role-policy --role-name {role} --policy-document file://setup-trust.json");
            foreach (var policy in policies)
            {
                script.Run($"aws iam attach-role-policy --role-name {role} --policy-arn arn:aws:iam::aws:policy/{policy}");
            }

            script.Set("role", $"aws iam get-role --role-name {role} --query Role.Arn --output text");
            script.Run($"gh variable set AWS_ROLE_ARN --repo \"$REPO\" {variable}--body \"$role\"");
        }

        if (spec.IsContainer)
        {
            script.Line();
            script.Comment("---- the build, which pushes the image from the branches that deploy");
            Role($"{spec.Name}-build", spec.DeployBranches().Select(branch => $"${{prefix}}:ref:refs/heads/{branch}"), "");
        }

        foreach (var environment in spec.Environments)
        {
            script.Line();
            script.Comment($"---- {environment.Name}");
            script.Run($"gh api --method PUT \"repos/$REPO/environments/{environment.Name}\"", quiet: true);
            Role($"{spec.Name}-{environment.Name}-deploy", [$"${{prefix}}:environment:{environment.Name}"], $"--env {environment.Name} ");
            GitHubSecrets(script, spec, environment);
        }

        script.Line();
        script.Remove("setup-trust.json");
        if (policies.Count == 0)
        {
            script.Echo("The roles have no permissions yet: attach the ones your deploy needs.");
        }
        else
        {
            script.Echo($"The roles got AWS's own policies ({string.Join(", ", policies)}): narrow them to your resources when you can.");
        }

        script.Echo("Done. Commit the workflow and push.");
        return script.ToFile(Path);
    }


    /// <summary>Google Cloud: a pool that trusts this repository's tokens, and a service account per environment that only that environment's jobs may use.</summary>
    private static GeneratedFile GitHubGoogle(PipelineSpec spec, bool powerShell)
    {
        var script = new Script(powerShell);
        script.Start(spec, "GitHub Actions", "Google Cloud", "`gcloud auth login` (as someone who may create service accounts and grant roles, with the project chosen) and `gh auth login`");
        script.Argument(1, "REPO", spec.Repository);
        script.Set("project", "gcloud config get-value project");
        // In PowerShell the program is a .cmd file, which stops at a parenthesis in an argument: the number is read from JSON there.
        script.Line(powerShell
            ? "$number = (gcloud projects describe \"$project\" --format json | ConvertFrom-Json).projectNumber; if ($LASTEXITCODE -ne 0) { throw 'The setup stopped: the command above failed.' }"
            : "number=$(gcloud projects describe \"$project\" --format \"value(projectNumber)\")");
        script.Set("repository", "gh api \"repos/$REPO\" --jq .id");
        GitHubPrefix(script);
        script.Echo("Repository $REPO ($prefix), project $project");
        script.Line();
        script.Unless("gcloud iam workload-identity-pools describe github --location global", "gcloud iam workload-identity-pools create github --location global --display-name GitHub --quiet");
        // The provider takes tokens of this repository alone, known by the ID that never changes.
        script.Unless(
            $"gcloud iam workload-identity-pools providers describe {spec.Name} --location global --workload-identity-pool github",
            $"gcloud iam workload-identity-pools providers create-oidc {spec.Name} --location global --workload-identity-pool github --issuer-uri https://token.actions.githubusercontent.com --attribute-mapping \"google.subject=assertion.sub,attribute.repository_id=assertion.repository_id\" --attribute-condition \"assertion.repository_id == '$repository'\" --quiet");
        script.Assign("provider", $"projects/$number/locations/global/workloadIdentityPools/github/providers/{spec.Name}");
        var roles = GoogleRoles(spec);

        void Account(string account, IEnumerable<string> subjects, string variable)
        {
            script.Assign("email", $"{account}@$project.iam.gserviceaccount.com");
            script.Unless("gcloud iam service-accounts describe \"$email\"", $"gcloud iam service-accounts create {account} --display-name \"{account}\" --quiet");
            foreach (var subject in subjects)
            {
                script.Run($"gcloud iam service-accounts add-iam-policy-binding \"$email\" --role roles/iam.workloadIdentityUser --member \"principal://iam.googleapis.com/projects/$number/locations/global/workloadIdentityPools/github/subject/{subject}\" --condition None --quiet", quiet: true);
            }

            foreach (var role in roles)
            {
                script.Run($"gcloud projects add-iam-policy-binding \"$project\" --member \"serviceAccount:$email\" --role {role} --condition None --quiet", quiet: true);
            }

            script.Run($"gh variable set GCP_WORKLOAD_IDENTITY_PROVIDER --repo \"$REPO\" {variable}--body \"$provider\"");
            script.Run($"gh variable set GCP_SERVICE_ACCOUNT --repo \"$REPO\" {variable}--body \"$email\"");
            script.Run($"gh variable set GCP_PROJECT_ID --repo \"$REPO\" {variable}--body \"$project\"");
        }

        if (spec.IsContainer)
        {
            script.Line();
            script.Comment("---- the build, which pushes the image from the branches that deploy");
            Account($"{spec.Name}-build", spec.DeployBranches().Select(branch => $"${{prefix}}:ref:refs/heads/{branch}"), "");
        }

        foreach (var environment in spec.Environments)
        {
            script.Line();
            script.Comment($"---- {environment.Name}");
            script.Run($"gh api --method PUT \"repos/$REPO/environments/{environment.Name}\"", quiet: true);
            Account($"{spec.Name}-{environment.Name}", [$"${{prefix}}:environment:{environment.Name}"], $"--env {environment.Name} ");
            GitHubSecrets(script, spec, environment);
        }

        script.Line();
        script.Echo("Every environment uses the project chosen in gcloud: for an environment in another project, choose it and run this again for that environment.");
        script.Echo("Done. Commit the workflow and push.");
        return script.ToFile(Path);
    }

